/**
 * Generate the Vim regex syntax file for `.lolo` — the fallback when the
 * tree-sitter parser is unavailable (and the only highlighter for the handful
 * of files the grammar cannot yet parse; see the plugin README).
 *
 * Ported rule-for-rule from `generateLoloTmLanguage()`. Vim resolves same-start
 * collisions by *definition order* (last wins) and always lets `:syn keyword`
 * beat a `:syn match`, so rules are emitted in reverse TextMate precedence.
 */
export function generateLoloVimSyntax(): string {
    const tokens = loadLoloTokens();
    const namespaced = namespacedOperators(tokens.operatorsByNamespace);
    const control = controlOperators(tokens.operatorsByNamespace);

    // `-` and `/` are word characters in lolo (render-ui, math/add, game-core),
    // so `:syn keyword` needs them in 'iskeyword' or it will never match them.
    return `" .lolo syntax — the regex fallback for Neovim without tree-sitter.
" GENERATED by ${GENERATED_BANNER}

if exists("b:current_syntax")
  finish
endif

syn iskeyword @,48-57,_,-,/,192-255
syn case match

" ── Lowest precedence first: Vim gives a later definition priority ──────────
syn match loloPunctuation "-->\\|--\\|[{}()\\[\\]:,|&]"
syn match loloModifier "[!*+]\\(\\s\\|$\\|,\\|)\\|\\]\\|}\\)\\@="
syn match loloNumber "-\\=\\<\\d\\+\\%(\\.\\d*\\)\\=\\>"
syn match loloArrow "->\\|→\\|::\\|="
syn match loloConstructor "\\<\\u\\w*\\>"
syn match loloUnknownOperator "\\<\\l[a-z0-9_]*/[a-z][a-z0-9/_-]*\\>"
syn match loloEvent "\\<\\u[A-Z0-9_]\\+\\>"
syn match loloReference "\\<\\u\\w*\\%(\\.\\a\\w*\\)\\+\\>"
syn match loloBinding "[@?]\\a[a-zA-Z0-9_.]*"

" ── Keywords always outrank matches at the same position ────────────────────
syn keyword loloKeyword ${[...tokens.loloKeywords].sort().join(' ')} as when every
syn keyword loloType ${[...tokens.loloPrimitiveTypes].sort().join(' ')}
syn keyword loloTypeConstructor Map Entity Event Orbital Page Trait
syn keyword loloPersistence ${[...tokens.loloPersistenceAndScope].sort().join(' ')}
syn keyword loloCategory ${[...tokens.loloTraitCategories].sort().join(' ')}
syn keyword loloBoolean true false
syn keyword loloNull null
syn keyword loloEffect ${[...tokens.effectTypes].sort().join(' ')}
syn keyword loloStdOperator ${[...new Set(namespaced)].sort().join(' ')}
syn keyword loloControl ${[...new Set(control)].sort().join(' ')}

" ── Strings and comments consume everything inside them ─────────────────────
syn match loloEscape +\\\\[ntr"\\\\/]+ contained
syn region loloString start=+"+ skip=+\\\\.+ end=+"+ contains=loloEscape,@Spell
syn region loloBlockComment start="#=" end="=#" contains=@Spell
syn match loloComment ";;.*$" contains=@Spell
syn match loloComment "#\\%(=\\)\\@!.*$" contains=@Spell

hi def link loloComment        Comment
hi def link loloBlockComment   Comment
hi def link loloString         String
hi def link loloEscape         SpecialChar
hi def link loloBinding        Identifier
hi def link loloReference      Type
hi def link loloEvent          Constant
hi def link loloKeyword        Keyword
hi def link loloEffect         Statement
hi def link loloControl        Conditional
hi def link loloStdOperator    Function
hi def link loloUnknownOperator Error
hi def link loloType           Type
hi def link loloTypeConstructor Type
hi def link loloPersistence    StorageClass
hi def link loloCategory       PreProc
hi def link loloConstructor    Structure
hi def link loloArrow          Operator
hi def link loloNumber         Number
hi def link loloBoolean        Boolean
hi def link loloNull           Constant
hi def link loloModifier       Operator
hi def link loloPunctuation    Delimiter

let b:current_syntax = "lolo"
`;
}

