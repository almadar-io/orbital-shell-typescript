// syntax/orb.vim — regex fallback
// ============================================================================

/**
 * Generate the Vim regex syntax file for `.orb`: stock JSON syntax plus the
 * s-expression injection, ported from `generateSExprGrammar()`'s lookaround
 * patterns (`(?<=")op(?=")` → `"\@<=op"\@=`).
 */
export function generateOrbVimSyntax(): string {
    const tokens = loadLoloTokens();
    const require = createRequire(import.meta.url);
    const rawTokens = JSON.parse(
        readFileSync(require.resolve('@almadar/syntax/tokens.json'), 'utf-8'),
    ) as { uiSlots?: string[] };

    const namespaced = namespacedOperators(tokens.operatorsByNamespace);
    const control = controlOperators(tokens.operatorsByNamespace);
    const arith = bareOperators(tokens.operatorsByNamespace);

    // Matched inside jsonString, anchored on the surrounding quotes so an
    // operator name never lights up inside prose. `#` delimits the pattern:
    // the usual `+` and `/` both occur *as operator names* in these lists.
    const inString = (name: string, alternation: string) =>
        `syn match ${name} #"\\@<=\\%(${alternation}\\)"\\@=# contained containedin=jsonString`;

    return `" .orb syntax — JSON plus the S-expression layer; the regex fallback for
" Neovim without tree-sitter.
" GENERATED by ${GENERATED_BANNER}

if exists("b:current_syntax")
  finish
endif

runtime! syntax/json.vim
unlet! b:current_syntax

${inString('orbStdOperator', vimAlternation(namespaced))}
${inString('orbOperator', vimAlternation(arith))}
${inString('orbControl', vimAlternation(control))}
${inString('orbEffect', vimAlternation(tokens.effectTypes))}
${inString('orbSlot', vimAlternation(rawTokens.uiSlots ?? []))}
${inString('orbBehavior', vimAlternation(tokens.behaviorNames))}
syn match orbBinding #"\\@<=@\\%(entity\\|payload\\|context\\|config\\|user\\|item\\|index\\)\\%(\\.[a-zA-Z_][a-zA-Z0-9_.]*\\)\\="\\@=# contained containedin=jsonString
syn match orbEvent #"\\@<=\\u[A-Z0-9_]\\{2,}"\\@=# contained containedin=jsonString

hi def link orbEffect       Statement
hi def link orbControl      Conditional
hi def link orbOperator     Operator
hi def link orbStdOperator  Function
hi def link orbBehavior     Function
hi def link orbBinding      Identifier
hi def link orbEvent        Constant
hi def link orbSlot         Tag

let b:current_syntax = "orb"
`;
}
