/**
 * Neovim Artifact Generator
 *
 * Generates the Neovim-side highlighting artifacts for `.lolo` and `.orb`:
 *
 * - `queries/lolo/highlights.scm` — tree-sitter query against the same
 *   `tree-sitter-lolo` grammar Zed uses, written with Neovim's standard
 *   capture names (`:h treesitter-highlight-groups`).
 * - `queries/orb/highlights.scm` — tree-sitter query for `.orb`, whose parser
 *   is the stock JSON grammar registered under the language name `orb` (see
 *   `editors/nvim/lua/almadar/treesitter.lua`); the s-expression layer is
 *   `#any-of?` predicates over `(string_content)`.
 * - `syntax/lolo.vim` / `syntax/orb.vim` — the regex fallback for Neovim
 *   builds without the tree-sitter parsers, ported from the TextMate grammar
 *   in `lolo-grammar.ts` / `sexpr-grammar.ts` rule-for-rule.
 *
 * Every token list is sourced from @almadar/syntax's `tokens.json` — the same
 * registry `lolo-grammar.ts` (VSCode + Zed) reads — so nothing here can drift
 * from the operator/pattern/behavior SSOT.
 *
 * Literal keywords are additionally intersected with the anonymous tokens the
 * real grammar declares (`tree-sitter-lolo/src/node-types.json`). A tree-sitter
 * query naming a token the parser has no node for fails to compile *as a
 * whole*, so a registry keyword the grammar has not caught up to (today:
 * `extends`) must be dropped from the query rather than silently breaking
 * every other rule in the file.
 *
 * @packageDocumentation
 */

import { createRequire } from 'node:module';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLoloTokens } from './lolo-grammar.js';

// ============================================================================
// Grammar introspection
// ============================================================================

/** This package's root: the nearest ancestor holding `package.json` (from `src/editor/` and `dist/` alike). */
function packageRoot(): string {
    let dir = dirname(fileURLToPath(import.meta.url));
    while (!existsSync(join(dir, 'package.json'))) {
        const parent = dirname(dir);
        if (parent === dir) throw new Error('nvim-grammar: no package.json above this module');
        dir = parent;
    }
    return dir;
}

/** Path to the tree-sitter-lolo grammar sources in this package. */
const GRAMMAR_DIR = join(packageRoot(), 'editors', 'zed', 'tree-sitter-lolo', 'src');

interface NodeTypeEntry {
    type: string;
    named: boolean;
}

export interface GrammarNodes {
    /** Named node types, e.g. `sexpr_op`, `entity_field`. */
    named: ReadonlySet<string>;
    /** Anonymous literal tokens, e.g. `"orbital"`, `"->"`, `"{"`. */
    anonymous: ReadonlySet<string>;
}

let cachedNodes: GrammarNodes | undefined;

/** Read the node types the generated `tree-sitter-lolo` parser actually declares. */
export function loadGrammarNodes(): GrammarNodes {
    if (cachedNodes) return cachedNodes;
    const raw = JSON.parse(
        readFileSync(join(GRAMMAR_DIR, 'node-types.json'), 'utf-8'),
    ) as NodeTypeEntry[];
    const named = new Set<string>();
    const anonymous = new Set<string>();
    for (const entry of raw) {
        (entry.named ? named : anonymous).add(entry.type);
    }
    cachedNodes = { named, anonymous };
    return cachedNodes;
}

// ============================================================================
// Shared helpers
// ============================================================================

const GENERATED_BANNER =
    '@almadar/syntax — regenerate with `pnpm run generate-grammar`. Do not edit.';

function scmHeader(what: string): string {
    return `; ${what}\n; GENERATED by ${GENERATED_BANNER}\n`;
}

/** Render a list as `#any-of?` arguments, one per line, sorted for stable diffs. */
function anyOfArgs(names: readonly string[], indent = '    '): string {
    return [...new Set(names)]
        .sort()
        .map((n) => `"${n.replace(/(["\\])/g, '\\$1')}"`)
        .join(`\n${indent}`);
}

/** Render a list as a tree-sitter alternation node list, wrapped at ~76 columns. */
function literalList(names: readonly string[], indent = '  '): string {
    return [...new Set(names)].sort().map((n) => `${indent}"${n}"`).join('\n');
}

function escapeRegex(str: string): string {
    return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Wrap a name in the literal double quotes a `.lolo` `string` token carries. */
function quoted(name: string): string {
    return `"${name}"`;
}

/**
 * Escape a literal for a Vim regex in *magic* mode — the default for `:syntax`.
 *
 * Only `\ . * [ ] ^ $ ~` are special there; `+ ? ( ) { } |` are literal and
 * become special only when backslash-escaped, so escaping them the JS way
 * (`escapeRegex`) would turn the operator name `+` into the quantifier `\+`.
 */
function vimEscape(str: string): string {
    return str.replace(/[\\.*[\]^$~]/g, '\\$&');
}

/** Longest-first alternation — a shorter operator must not shadow a longer one. */
function vimAlternation(words: readonly string[]): string {
    return [...new Set(words)]
        .sort((a, b) => b.length - a.length || a.localeCompare(b))
        .map(vimEscape)
        .join('\\|');
}

/** All namespaced runtime operators (`math/add`, `array/map`, …) across namespaces. */
function namespacedOperators(byNamespace: Record<string, string[]>): string[] {
    return Object.values(byNamespace)
        .flat()
        .filter((op) => op.includes('/'));
}

/** Control-flow + logic s-expr operators (`if`, `and`, `let`, `do`, `fn`, …). */
function controlOperators(byNamespace: Record<string, string[]>): string[] {
    return [...(byNamespace.control ?? []), ...(byNamespace.logic ?? [])];
}

/**
 * Bare arithmetic/comparison operators (`+`, `-`, `=`, `<=`, …).
 *
 * The registry's `arithmetic` and `comparison` buckets are mixed: they hold
 * both the bare symbolic operators and namespaced calls (`math/randomInt`,
 * `validate/required`). Only the bare ones belong to the operator colour —
 * the namespaced ones are picked up by `namespacedOperators`.
 */
function bareOperators(byNamespace: Record<string, string[]>): string[] {
    return [...(byNamespace.arithmetic ?? []), ...(byNamespace.comparison ?? [])]
        .filter((op) => !op.includes('/'));
}

