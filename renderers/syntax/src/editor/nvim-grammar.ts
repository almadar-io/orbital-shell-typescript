/**
 * Generate the Neovim tree-sitter highlights query for `.lolo`.
 *
 * Capture names are Neovim's standard groups, not Zed's. Precedence is
 * tree-sitter's: for the same node, a *later* pattern wins — so each generic
 * rule is stated first and the registry-driven `#any-of?` refinements follow.
 */
export function generateLoloNvimHighlights(): string {
    const tokens = loadLoloTokens();
    const { anonymous } = loadGrammarNodes();

    // Only literals the parser really has — see the module doc.
    const declarationKeywords = tokens.loloKeywords.filter((k) => anonymous.has(k));
    // Grammar-only keywords the token registry does not carry as `loloKeywords`.
    const extraKeywords = ['as', 'when', 'every', 'events', 'fields', 'emitsScope']
        .filter((k) => anonymous.has(k));
    const typeConstructors = ['Map', 'Entity', 'Event', 'Orbital', 'Page', 'Trait']
        .filter((k) => anonymous.has(k));

    const control = controlOperators(tokens.operatorsByNamespace);
    const namespaced = namespacedOperators(tokens.operatorsByNamespace);

    return `${scmHeader('.lolo — Neovim tree-sitter highlights')}
; ── Comments ────────────────────────────────────────────────────────────────
(comment) @comment @spell

; ── Declaration keywords ────────────────────────────────────────────────────
[
${literalList([...declarationKeywords, ...extraKeywords])}
] @keyword

${anonymous.has('@rebindable') ? '"@rebindable" @attribute\n' : ''}
; ── Built-in type constructors ──────────────────────────────────────────────
[
${literalList(typeConstructors)}
] @type.builtin

; ── Literals ────────────────────────────────────────────────────────────────
(string) @string
(number) @number
(boolean) @boolean
(null) @constant.builtin
(version_tag) @string.special
(duration) @number

; ── Bindings: @entity.field, @config.x, ?payload.field ──────────────────────
(sigil) @variable.builtin
(payload_sigil) @variable.builtin

; ── Events ──────────────────────────────────────────────────────────────────
(event_name) @constant
(event_arrow) @operator

; ── Declaration names ───────────────────────────────────────────────────────
(orbital name: (identifier) @type)
(entity name: (identifier) @type)
(trait name: (identifier) @type)
(trait entity: (identifier) @type)
(page name: (identifier) @type)
(page trait: (identifier) @type)
(page path: (string) @string.special.path)
(type_alias name: (identifier) @type)
(type_alias param: (identifier) @type.parameter)
(use_decl path: (string) @string.special.path)
(use_decl alias: (identifier) @type)
(dotted_reference (identifier) @type)
(dotted_reference (event_name) @constant)

; ── Members ─────────────────────────────────────────────────────────────────
(entity_field name: (identifier) @variable.member)
(config_field name: (identifier) @variable.member)
(type_object name: (identifier) @variable.member)
(object_literal key: (identifier) @variable.member)
(object_literal key: (string) @variable.member)
(state_block name: (identifier) @label)
(tick_decl name: (identifier) @function)
(emits_scope scope: (identifier) @keyword.modifier)
(emit_decl scope: (identifier) @keyword.modifier)

; ── Types ───────────────────────────────────────────────────────────────────
(type_atom (identifier) @type)
((type_atom (identifier) @type.builtin)
  (#any-of? @type.builtin
    ${anyOfArgs(tokens.loloPrimitiveTypes)}))

; ── Bracket tags: [runtime], [interaction], [shared] ────────────────────────
(bracket_tag key: (identifier) @constant.builtin)
(bracket_tag value: (identifier) @constant)
((bracket_tag key: (identifier) @keyword.modifier)
  (#any-of? @keyword.modifier
    ${anyOfArgs(tokens.loloPersistenceAndScope)}))
((bracket_tag key: (identifier) @attribute)
  (#any-of? @attribute
    ${anyOfArgs(tokens.loloTraitCategories)}))

; ── Annotations: @description, @synonyms, @label, @tier, … ──────────────────
(annotation_tag) @attribute

; ── JSX ─────────────────────────────────────────────────────────────────────
(jsx_tag_name) @tag
(jsx_attribute name: (identifier) @tag.attribute)

; ── S-expressions ───────────────────────────────────────────────────────────
; The call head is the FIRST NAMED CHILD of \`sexpr\`, not a \`sexpr_op\`:
; \`sexpr_op\` only materializes for symbol heads (\`(+ 1 2)\`, \`(= a b)\`)
; because of the declared \`[sexpr_op, _sexpr_arg]\` GLR conflict — for the
; overwhelmingly common identifier head (\`(set …)\`, \`(math/add …)\`) the
; \`_sexpr_arg\` parse wins and the head is a bare \`identifier\`. Anchoring on
; the first named child covers both shapes.
; Generic call head first; the registry-driven refinements below override it.
(sexpr . (identifier) @function)
(sexpr_op (operator_symbol) @operator)
(sexpr_op "=" @operator)

; Namespaced runtime operators: math/add, array/map, str/join, …
((sexpr . (identifier) @function.builtin)
  (#any-of? @function.builtin
    ${anyOfArgs(namespaced)}))

; Control-flow / logic operators: if, and, or, not, let, do, fn, …
((sexpr . (identifier) @keyword.conditional)
  (#any-of? @keyword.conditional
    ${anyOfArgs(control)}))

; Effect operators: set, emit, persist, fetch, render-ui, navigate, …
((sexpr . (identifier) @keyword.function)
  (#any-of? @keyword.function
    ${anyOfArgs(tokens.effectTypes)}))

; ── Registry names inside string literals ───────────────────────────────────
; \`string\` is an atomic token in this grammar (quotes included, no
; \`string_content\` child), so the predicates match the quoted form.
((string) @type.builtin
  (#any-of? @type.builtin
    ${anyOfArgs(tokens.patternNames.map(quoted))}))

((string) @function.builtin
  (#any-of? @function.builtin
    ${anyOfArgs(tokens.behaviorNames.map(quoted))}))

; ── Punctuation ─────────────────────────────────────────────────────────────
[
  "("
  ")"
  "["
  "]"
  "{"
  "}"
] @punctuation.bracket

[
  ","
  ":"
  "::"
  "."
] @punctuation.delimiter

(arrow) @operator

[
  "="
  "!"
  "*"
  "+"
  "?"
  "|"
  "&"
] @operator
`;
}

