/**
 * Generate the Neovim tree-sitter highlights query for `.orb`.
 *
 * `.orb` is JSON, so the parser is the stock `json` grammar loaded under the
 * language name `orb`; the s-expression layer rides on `(string_content)`
 * predicates. Unlike the hand-written Zed equivalent this is generated from
 * the operator registry, so a new operator is coloured on the next build.
 */
export function generateOrbNvimHighlights(): string {
    const tokens = loadLoloTokens();
    const require = createRequire(import.meta.url);
    const rawTokens = JSON.parse(
        readFileSync(require.resolve('@almadar/syntax/tokens.json'), 'utf-8'),
    ) as { uiSlots?: string[]; structuralKeys?: string[] };

    const control = controlOperators(tokens.operatorsByNamespace);
    const namespaced = namespacedOperators(tokens.operatorsByNamespace);
    const bare = bareOperators(tokens.operatorsByNamespace);

    return `${scmHeader('.orb — Neovim tree-sitter highlights (JSON grammar under language `orb`)')}
; ── JSON base ───────────────────────────────────────────────────────────────
(pair key: (string) @variable.member)
(string) @string
(number) @number
[(true) (false)] @boolean
(null) @constant.builtin
["{" "}" "[" "]"] @punctuation.bracket
["," ":"] @punctuation.delimiter
(comment) @comment @spell

; ── S-expression layer (arrays of strings inside the IR) ────────────────────
; Namespaced runtime operators: math/add, array/map, str/join, …
((string_content) @function.builtin
  (#any-of? @function.builtin
    ${anyOfArgs(namespaced)}))

; Arithmetic / comparison operators
((string_content) @operator
  (#any-of? @operator
    ${anyOfArgs(bare)}))

; Control-flow / logic operators
((string_content) @keyword.conditional
  (#any-of? @keyword.conditional
    ${anyOfArgs(control)}))

; Effect operators
((string_content) @keyword.function
  (#any-of? @keyword.function
    ${anyOfArgs(tokens.effectTypes)}))

; UI slots: main, sidebar, modal, hud-top, …
((string_content) @tag
  (#any-of? @tag
    ${anyOfArgs(rawTokens.uiSlots ?? [])}))

; UI pattern names
((string_content) @markup.link
  (#any-of? @markup.link
    ${anyOfArgs(tokens.patternNames)}))

; Behavior names: std-browse, std-calendar, …
((string_content) @function
  (#any-of? @function
    ${anyOfArgs(tokens.behaviorNames)}))

; Bindings: @entity.*, @payload.*, @context.*, @config.*, @user.*
; \`#match?\` compiles with Vim's regex engine in VERY MAGIC mode — Neovim
; prepends \`\\v\` (\`runtime/lua/vim/treesitter/query.lua\`, check_magic).
; So \`(\`/\`|\`/\`{\` are PCRE-like, but \`@\` is the operator prefix
; (\`@=\`, \`@<=\`) and a literal \`@\` must be escaped. Tree-sitter also
; strips one backslash off every escape in a query string, hence \`\\\\@\`
; here to reach the engine as \`\\@\`.
((string_content) @variable.builtin
  (#match? @variable.builtin "^\\\\@(entity|payload|context|config|user|item|index)(\\\\.|$)"))

; Event keys: UPPER_SNAKE_CASE
((string_content) @constant
  (#match? @constant "^[A-Z][A-Z0-9_]{2,}$"))

; ── Structural keys of the .orb IR ──────────────────────────────────────────
; Last, so an object KEY always outranks the value-shaped rules above — a key
; that happens to spell a pattern or operator name stays a key.
((pair key: (string (string_content) @keyword))
  (#any-of? @keyword
    ${anyOfArgs(rawTokens.structuralKeys ?? [])}))
`;
}

