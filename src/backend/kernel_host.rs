impl TypeScriptBackend {
    /// The shared barrel of a kernel-hosted app: the default exports plus the embedded program.
    pub(crate) fn generate_shared_index_kernel(&self) -> InternalFile {
        let base = self.generate_shared_index();
        InternalFile::new(
            base.path,
            format!("{}export * from './program.js';\nexport * from './dispatch.js';\n", base.content),
            GeneratedFileType::Barrel,
        )
    }

    /// The embedded program: the resolved schema as JSON and the module that parses it.
    pub(crate) fn generate_kernel_program(&self) -> Vec<InternalFile> {
        let Some(schema) = &self.browser_schema else {
            return Vec::new();
        };
        let Ok(json) = serde_json::to_string(schema) else {
            return Vec::new();
        };
        vec![
            InternalFile::new(
                "packages/shared/src/program.json",
                json,
                GeneratedFileType::Config,
            ),
            InternalFile::new(
                "packages/shared/src/dispatch.ts",
                SHARED_DISPATCH,
                GeneratedFileType::Config,
            ),
            InternalFile::new(
                "packages/shared/src/program.ts",
                SHARED_PROGRAM,
                GeneratedFileType::Config,
            ),
        ]
    }

    /// The kernel-hosted client: the loader and the `App` that renders the program on the kernel.
    pub(crate) fn generate_kernel_client(&self, module: &OirModule) -> Vec<InternalFile> {
        let (locale_file, locale, direction) = match self.schema_language.as_str() {
            "ar" => ("ar.json", "ar", "rtl"),
            "sl" => ("sl.json", "sl", "ltr"),
            _ => ("en.json", "en", "ltr"),
        };
        let (theme_import, theme_props) = if module.themes.is_empty() {
            ("", "")
        } else {
            (
                "import { THEMES, DEFAULT_THEME, DEFAULT_MODE } from './generated/theme-config';\n",
                " themes={THEMES} defaultTheme={DEFAULT_THEME} defaultMode={DEFAULT_MODE}",
            )
        };
        let app = CLIENT_APP
            .replace("__LOCALE_FILE__", locale_file)
            .replace("__LOCALE__", locale)
            .replace("__DIRECTION__", direction)
            .replace("__THEME_IMPORT__", theme_import)
            .replace("__THEME_PROPS__", theme_props);
        vec![
            InternalFile::new(
                "packages/client/src/kernel-host.ts",
                CLIENT_LOADER,
                GeneratedFileType::Config,
            ),
            InternalFile::new(
                "packages/client/src/App.tsx",
                app,
                GeneratedFileType::Config,
            ),
        ]
    }

    /// The kernel-hosted server: the host that opens the kernel and the single route mount.
    pub(crate) fn generate_kernel_server(&self) -> Vec<InternalFile> {
        match self.server_framework {
            ServerFramework::Express => vec![
                InternalFile::new("packages/server/src/kernel-host.ts", SERVER_HOST, GeneratedFileType::Config),
                InternalFile::new("packages/server/src/routes.ts", SERVER_ROUTES, GeneratedFileType::Route),
            ],
            ServerFramework::Hono => vec![
                InternalFile::new("packages/server/src/kernel-host.ts", server_host_hono(), GeneratedFileType::Config),
                InternalFile::new("packages/server/src/kernel-routes.ts", KERNEL_ROUTES_HONO, GeneratedFileType::Route),
                InternalFile::new("packages/server/src/routes.ts", SERVER_ROUTES_HONO, GeneratedFileType::Route),
            ],
        }
    }

    /// What a kernel-hosted compile could not do, reported with the output.
    pub(crate) fn kernel_host_warnings(&self) -> Vec<String> {
        if self.browser_schema.is_none() {
            vec![
                "kernel host: no resolved schema was supplied, so the program is not embedded"
                    .to_string(),
            ]
        } else {
            Vec::new()
        }
    }
}
