/// The server host on Hono: the same kernel, opened by the same code, without the Express router.
fn server_host_hono() -> String {
    let tail = SERVER_HOST.find("let opened: Promise<OpenedHost> | undefined;").expect("the host's tail");
    let head = SERVER_HOST[..tail]
        .replace("import type { RequestHandler, Router } from 'express';\n", "")
        .replace("import { logger } from '@almadar/server';", "import { logger } from '@almadar/server-hono';")
        .replace("  router: Router;\n", "")
        .replace("return { runtime, router: runtime.router() };", "return { runtime };");
    format!(
        "{head}let opened: Promise<OpenedHost> | undefined;\n\n/** Opens the kernel once; every caller shares the one program instance. */\nexport async function kernelRuntime(): Promise<OrbitalServerRuntime> {{\n  opened ??= open();\n  return (await opened).runtime;\n}}\n\n/** An inbound delivery (`POST /api/hooks/:name`), answered by the kernel once it is open (EXEC-INBOUND-1). */\nexport async function deliverInbound(name: string, delivery: InboundDelivery): Promise<InboundAnswer> {{\n  return (await kernelRuntime()).deliverInbound(name, delivery);\n}}\n\n/** Starts the kernel at boot so the first request does not pay for it; a failure is logged and every request then fails with it. */\nexport function warmKernelHost(): void {{\n  kernelRuntime().catch((error: Error) => logger.error(`Kernel host failed to start: ${{error.message}}`));\n}}\n"
    )
}



