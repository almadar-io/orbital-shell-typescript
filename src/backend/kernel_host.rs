/// Top-level keys the client never reads: `_metadata` and `ledger` are read only by the builders and
/// behavior composition, never by `OrbPreview`, the client kernel or the wasm kernel (which is handed
/// `{ name, orbitals }` only).
const CLIENT_UNREAD_PROGRAM_KEYS: [&str; 2] = ["_metadata", "ledger"];

/// Per-trait keys the client never reads: the wasm kernel's schema types carry them but no kernel
/// code reads them, and `sourceEntityDefinition` is read only by the `autoMock` preview path, which a
/// transport-backed `OrbPreview` skips.
const CLIENT_UNREAD_TRAIT_KEYS: [&str; 2] = ["effectRow", "sourceEntityDefinition"];

/// The program with every object's keys in sorted order. The schema's maps (`config`, ...) are hash maps, so
/// two resolves of one program would otherwise embed the same data in different byte orders.
fn with_sorted_keys(value: serde_json::Value) -> serde_json::Value {
    match value {
        serde_json::Value::Object(map) => {
            let mut entries: Vec<(String, serde_json::Value)> = map.into_iter().collect();
            entries.sort_by(|a, b| a.0.cmp(&b.0));
            serde_json::Value::Object(entries.into_iter().map(|(k, v)| (k, with_sorted_keys(v))).collect())
        }
        serde_json::Value::Array(items) => {
            serde_json::Value::Array(items.into_iter().map(with_sorted_keys).collect())
        }
        other => other,
    }
}

/// The resolved program as the browser receives it. The server keeps the whole program.
/// The program's files the program-independent web client reads at startup, by path under the
/// client's public root: `client.json` (the `ClientManifest`), `themes.css` (the declared themes, or
/// the runtime default preset when it declares none) and, when its browser kernel needs it,
/// `language.json`. `orb compile` writes them into `packages/client/public/`; `orb serve` serves them
/// beside the prebuilt client.
pub fn client_runtime_files(module: &OirModule, language: &str, ships_language: bool) -> Vec<(String, String)> {
    let (locale, direction) = match language {
        "ar" => ("ar", "rtl"),
        "sl" => ("sl", "ltr"),
        _ => ("en", "ltr"),
    };
    let (themes, default_theme, default_mode) = crate::codegen::client_themes(&module.themes, module.default_theme.as_deref());
    let manifest = serde_json::json!({
        "locale": locale,
        "direction": direction,
        "themes": themes,
        "defaultTheme": default_theme,
        "defaultMode": default_mode,
        "language": ships_language,
    });
    let default_preset;
    let styled: &[orbital_core_base::schema::types::ThemeDefinition] = if module.themes.is_empty() {
        default_preset = orbital_core_base::theme::ThemePresets::installed()
            .get(orbital_core_base::theme::DEFAULT_THEME_BASE)
            .cloned()
            .into_iter()
            .collect::<Vec<_>>();
        &default_preset
    } else {
        &module.themes
    };
    let mut css = String::new();
    for url in crate::codegen::theme_font_imports(styled) {
        css.push_str(&format!("@import url(\"{url}\");\n"));
    }
    for theme in styled {
        css.push_str(&crate::codegen::generate_theme_css(theme));
        css.push('\n');
    }
    let mut files = vec![
        ("client.json".to_string(), serde_json::to_string_pretty(&manifest).unwrap_or_default()),
        ("themes.css".to_string(), css),
    ];
    if ships_language {
        if let Ok(bundle) = orbital_core_base::language_data::language_bundle_json() {
            files.push(("language.json".to_string(), bundle));
        }
    }
    files
}

/// `program.client.json`: the resolved program as the web client fetches it (keys sorted, without what no
/// client code path reads).
pub fn client_program_json(schema: &orbital_core_base::schema::types::OrbitalSchema) -> serde_json::Result<String> {
    serde_json::to_string(&client_program(&with_sorted_keys(serde_json::to_value(schema)?)))
}

pub(crate) fn client_program(program: &serde_json::Value) -> serde_json::Value {
    let mut projected = program.clone();
    let Some(root) = projected.as_object_mut() else {
        return projected;
    };
    for key in CLIENT_UNREAD_PROGRAM_KEYS {
        root.remove(key);
    }
    if let Some(orbitals) = root
        .get_mut("orbitals")
        .and_then(serde_json::Value::as_array_mut)
    {
        for orbital in orbitals {
            let traits = orbital
                .get_mut("traits")
                .and_then(serde_json::Value::as_array_mut);
            for trait_def in traits.into_iter().flatten() {
                if let Some(trait_def) = trait_def.as_object_mut() {
                    for key in CLIENT_UNREAD_TRAIT_KEYS {
                        trait_def.remove(key);
                    }
                }
            }
        }
    }
    projected
}

impl TypeScriptBackend {
    /// The shared barrel of a kernel-hosted app: the default exports plus the embedded program.
    pub(crate) fn generate_shared_index_kernel(&self) -> InternalFile {
        let base = self.generate_shared_index();
        InternalFile::new(
            base.path,
            format!(
                "{}export * from './program.js';\nexport * from './dispatch.js';\n",
                base.content
            ),
            GeneratedFileType::Barrel,
        )
    }

    /// The embedded program: the resolved schema as JSON and the module that parses it.
    pub(crate) fn generate_kernel_program(&self) -> Vec<InternalFile> {
        let Some(schema) = &self.browser_schema else {
            return Vec::new();
        };
        let Ok(value) = serde_json::to_value(schema) else {
            return Vec::new();
        };
        let Ok(json) = serde_json::to_string(&with_sorted_keys(value)) else {
            return Vec::new();
        };
        vec![
            InternalFile::new(
                "packages/shared/src/program.json",
                json,
                GeneratedFileType::Config,
            ),
            InternalFile::new(
                "packages/shared/src/dispatch.ts",
                SHARED_DISPATCH,
                GeneratedFileType::Config,
            ),
            InternalFile::new(
                "packages/shared/src/program.ts",
                SHARED_PROGRAM,
                GeneratedFileType::Config,
            ),
        ]
    }

    /// The kernel-hosted client: the loader and the `App` that renders the program on the kernel.
    pub(crate) fn generate_kernel_client(&self, module: &OirModule) -> Vec<InternalFile> {
        let ships_language = self.client_needs_language(module);
        let mut files: Vec<InternalFile> = Vec::new();
        files.extend(client_runtime_files(module, &self.schema_language, ships_language).into_iter().map(|(path, content)| {
            InternalFile::new(format!("packages/client/public/{path}"), content, GeneratedFileType::Config)
        }));
        files.extend(self.generate_client_program_files());
        files
    }

    /// The client's projection of the program, a static asset the template client fetches at startup.
    fn generate_client_program_files(&self) -> Vec<InternalFile> {
        let Some(schema) = &self.browser_schema else {
            return Vec::new();
        };
        let Ok(json) = client_program_json(schema) else {
            return Vec::new();
        };
        vec![
            InternalFile::new(
                "packages/client/public/program.client.json",
                json,
                GeneratedFileType::Config,
            ),
        ]
    }

    /// The kernel-hosted server: the host that opens the kernel and the single route mount.
    pub(crate) fn generate_kernel_server(&self) -> Vec<InternalFile> {
        vec![
            InternalFile::new("packages/server/src/kernel-host.ts", SERVER_HOST, GeneratedFileType::Config),
            InternalFile::new("packages/server/src/routes.ts", SERVER_ROUTES, GeneratedFileType::Route),
        ]
    }

    /// What a kernel-hosted compile could not do, reported with the output.
    /// The client may open a kernel over browser-stored rows: the program stores some, or it has lazy pages, whose
    /// behaviors load after compile and may store their own.
    fn client_needs_language(&self, module: &OirModule) -> bool {
        let has_lazy_pages = self
            .browser_schema
            .as_ref()
            .and_then(|schema| schema.lazy_pages.as_ref())
            .is_some_and(|pages| !pages.is_empty());
        has_lazy_pages || module.entities.iter().any(|entity| entity.local)
    }

    pub(crate) fn kernel_host_warnings(&self, module: &OirModule) -> Vec<String> {
        let mut warnings = Vec::new();
        if self.browser_schema.is_none() {
            warnings.push("kernel host: no resolved schema was supplied, so the program is not embedded".to_string());
        }
        if self.target != "server" && self.client_needs_language(module) {
            if let Err(e) = orbital_core_base::language_data::language_bundle_json() {
                warnings.push(format!("kernel host: the program stores rows in the browser (or has lazy pages that may), but the installed language could not be read for its browser kernel ({}: {e})", e.code()));
            }
        }
        warnings
    }
}

#[cfg(test)]
mod client_program_tests {
    use super::{client_program, with_sorted_keys};
    use serde_json::json;

    fn program() -> serde_json::Value {
        json!({
            "name": "App",
            "_metadata": { "configProvenance": { "T": [] } },
            "ledger": { "entries": {} },
            "orbitals": [{
                "name": "O",
                "entity": { "name": "E" },
                "traits": [
                    { "name": "T", "effectRow": { "uses": [] }, "sourceEntityDefinition": { "name": "E" },
                      "emits": [{ "event": "X", "eventId": "evt_1", "description": "d" }],
                      "stateMachine": { "transitions": [{ "event": "X", "eventId": "evt_1" }] } },
                    { "ref": "Imported" }
                ]
            }]
        })
    }

    #[test]
    fn the_unread_keys_are_dropped_everywhere_they_occur() {
        let out = client_program(&program());
        assert!(out.get("_metadata").is_none() && out.get("ledger").is_none());
        let t = &out["orbitals"][0]["traits"][0];
        assert!(t.get("effectRow").is_none() && t.get("sourceEntityDefinition").is_none());
    }

    #[test]
    fn control_every_key_a_client_path_reads_survives() {
        let out = client_program(&program());
        let t = &out["orbitals"][0]["traits"][0];
        assert_eq!(t["emits"][0]["eventId"], "evt_1");
        assert_eq!(t["emits"][0]["description"], "d");
        assert_eq!(t["stateMachine"]["transitions"][0]["eventId"], "evt_1");
        assert_eq!(out["orbitals"][0]["traits"][1]["ref"], "Imported");
        assert_eq!(out["orbitals"][0]["entity"]["name"], "E");
    }

    #[test]
    fn edge_a_program_that_is_not_an_object_passes_through() {
        assert_eq!(client_program(&json!(null)), json!(null));
    }

    #[test]
    fn keys_are_sorted_at_every_depth_and_array_order_is_kept() {
        let out = with_sorted_keys(json!({ "b": 1, "a": { "z": [ { "y": 1, "x": 2 }, 0 ], "c": null } }));
        assert_eq!(
            serde_json::to_string(&out).unwrap(),
            r#"{"a":{"c":null,"z":[{"x":2,"y":1},0]},"b":1}"#
        );
    }

    #[test]
    fn edge_a_scalar_passes_through_unchanged() {
        assert_eq!(with_sorted_keys(json!("k")), json!("k"));
    }
}

