//! what is emitted is only the host glue around it. The server answers each `Await` of the kernel
//! through `@almadar/runtime`'s kernel engine; the client hands the same resolved schema to the
//! `@almadar/ui` renderer under `KernelEngineProvider engine="kernel"`.

