use crate::backend::*;

impl TypeScriptBackend {
    /// Generate `packages/server/src/i18n.ts` for a program with `locales`: the server's
    /// `i18n/t`, evaluated with the requesting viewer's locale (`OrbitalEventRequest.locale`,
    /// absent → the first declared locale), the compiled twin of the runtime's `evalI18nT`.
    pub(crate) fn generate_server_i18n_module(&self, locales: &[String]) -> Option<InternalFile> {
        if locales.is_empty() {
            return None;
        }
        Some(InternalFile::new(
            "packages/server/src/i18n.ts",
            render_server_i18n_module(locales),
            GeneratedFileType::Config,
        ))
    }
}

pub(crate) fn render_server_i18n_module(locales: &[String]) -> String {
    let mut code = String::new();
    code.push_str("/**\n * The server's `i18n/t`: messages from the program's catalogs, in the requesting viewer's locale.\n *\n");
    code.push_str(" * @generated by Orbital Compiler\n * @packageDocumentation\n */\n\n");
    code.push_str("import { AsyncLocalStorage } from 'node:async_hooks';\n");
    for locale in locales {
        code.push_str(&format!(
            "import messages_{locale} from '../../../locales/{locale}.json';\n"
        ));
    }
    let entries: Vec<String> = locales
        .iter()
        .map(|l| format!("{l}: messages_{l}"))
        .collect();
    code.push_str(&format!(
        "\nconst MESSAGES: Readonly<Record<string, Readonly<Record<string, string>>>> = {{ {} }};\n",
        entries.join(", ")
    ));
    code.push_str(&format!("const DEFAULT_LOCALE = '{}';\n", locales[0]));
    code.push_str("const requestLocale = new AsyncLocalStorage<string>();\n\n");
    code.push_str("/** Runs one event request with its viewer's locale; a locale the program does not declare is an error. */\n");
    code.push_str("export function withLocale<T>(locale: string | undefined, run: () => T): T {\n");
    code.push_str("  const active = locale ?? DEFAULT_LOCALE;\n");
    code.push_str("  if (MESSAGES[active] === undefined) {\n");
    code.push_str("    throw new Error(`locale \"${active}\" is not one of the program's declared locales [${Object.keys(MESSAGES).join(', ')}]`);\n");
    code.push_str("  }\n");
    code.push_str("  return requestLocale.run(active, run);\n");
    code.push_str("}\n\n");
    code.push_str("/** The requesting viewer's locale (`@locale` on the server). */\n");
    code.push_str("export function currentLocale(): string {\n");
    code.push_str("  return requestLocale.getStore() ?? DEFAULT_LOCALE;\n");
    code.push_str("}\n\n");
    code.push_str("/** The active locale's message for a catalog key, with `{{name}}` placeholders filled; a missing message is an error. */\n");
    code.push_str(
        "export function __t(key: string, params?: Readonly<Record<string, string>>): string {\n",
    );
    code.push_str("  const locale = requestLocale.getStore() ?? DEFAULT_LOCALE;\n");
    code.push_str("  const message = MESSAGES[locale]?.[key];\n");
    code.push_str("  if (message === undefined) {\n");
    code.push_str("    throw new Error(`i18n/t: no \\`${locale}\\` message for \\`${key}\\``);\n");
    code.push_str("  }\n");
    code.push_str("  if (params === undefined) return message;\n");
    code.push_str("  let out = message;\n");
    code.push_str("  for (const [name, value] of Object.entries(params)) {\n");
    code.push_str("    out = out.split(`{{${name}}}`).join(value);\n");
    code.push_str("  }\n");
    code.push_str("  return out;\n");
    code.push_str("}\n");
    code
}

const VIEWER_IMPORT: &str = "import { viewerOf } from '../../../viewer.js';\n";
const RUN_EVENT_HEAD: &str = "export async function runEvent(body: EventRequest, user: UserContext | undefined): Promise<EventResponse> {\n";

/// A handler file of a program with `locales` runs each request under its viewer's locale
/// (`withLocale`) and evaluates `i18n/t` through the server's catalogs (`__t`).
pub(crate) fn localize_handler_file(code: String, locales: &[String]) -> String {
    if locales.is_empty() || !code.contains(RUN_EVENT_HEAD) {
        return code;
    }
    let mut names = Vec::new();
    if code.contains("__t(") {
        names.push("__t");
    }
    if code.contains("currentLocale()") {
        names.push("currentLocale");
    }
    names.push("withLocale");
    let symbols = names.join(", ");
    let import = format!("{VIEWER_IMPORT}import {{ {symbols} }} from '../../../i18n.js';\n");
    let wrapped = format!(
        "{RUN_EVENT_HEAD}  return withLocale(body.locale, () => runEventInLocale(body, user));\n}}\n\nasync function runEventInLocale(body: EventRequest, user: UserContext | undefined): Promise<EventResponse> {{\n"
    );
    code.replacen(VIEWER_IMPORT, &import, 1)
        .replacen(RUN_EVENT_HEAD, &wrapped, 1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_declared_locale_catalog_is_imported_and_the_first_is_the_default() {
        let ts = render_server_i18n_module(&["en".into(), "ar".into(), "sl".into()]);
        assert!(
            ts.contains("import messages_en from '../../../locales/en.json';"),
            "{ts}"
        );
        assert!(
            ts.contains("import messages_sl from '../../../locales/sl.json';"),
            "{ts}"
        );
        assert!(
            ts.contains("= { en: messages_en, ar: messages_ar, sl: messages_sl };"),
            "{ts}"
        );
        assert!(ts.contains("const DEFAULT_LOCALE = 'en';"), "{ts}");
    }

    #[test]
    fn a_missing_message_and_an_undeclared_locale_throw_rather_than_fall_back() {
        let ts = render_server_i18n_module(&["ar".into()]);
        assert!(ts.contains("const DEFAULT_LOCALE = 'ar';"), "{ts}");
        assert!(
            ts.contains("throw new Error(`i18n/t: no \\`${locale}\\` message for \\`${key}\\``);"),
            "{ts}"
        );
        assert!(
            ts.contains("is not one of the program's declared locales"),
            "{ts}"
        );
        assert!(!ts.contains("?? key"), "no key fallback: {ts}");
    }

    fn handler(body: &str) -> String {
        format!("{VIEWER_IMPORT}\n{RUN_EVENT_HEAD}  const {{ event }} = body;\n{body}\n}}\n")
    }

    #[test]
    fn a_localized_handler_runs_each_request_under_its_viewer_locale() {
        let ts = localize_handler_file(
            handler("  const x = __t(\"a:b\");"),
            &["en".into(), "ar".into()],
        );
        assert!(
            ts.contains("import { __t, withLocale } from '../../../i18n.js';"),
            "{ts}"
        );
        assert!(
            ts.contains("  return withLocale(body.locale, () => runEventInLocale(body, user));\n}"),
            "{ts}"
        );
        assert!(ts.contains("async function runEventInLocale(body: EventRequest, user: UserContext | undefined): Promise<EventResponse> {\n  const { event } = body;"), "{ts}");
        assert_eq!(
            ts.matches("export async function runEvent(").count(),
            1,
            "{ts}"
        );
    }

    #[test]
    fn a_handler_without_i18n_t_imports_only_with_locale() {
        let ts = localize_handler_file(handler("  const x = 1;"), &["en".into()]);
        assert!(
            ts.contains("import { withLocale } from '../../../i18n.js';"),
            "{ts}"
        );
        assert!(!ts.contains("__t"), "{ts}");
    }

    #[test]
    fn control_a_program_without_locales_is_untouched() {
        let original = handler("  const x = 1;");
        assert_eq!(localize_handler_file(original.clone(), &[]), original);
    }

    #[test]
    fn control_a_program_without_locales_gets_no_module() {
        assert!(TypeScriptBackend::new()
            .generate_server_i18n_module(&[])
            .is_none());
    }
}
