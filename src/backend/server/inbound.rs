//! `packages/server/src/inbound.ts`: the program's inbound handlers (`/api/hooks/<name>`,
//! EXEC-INBOUND-1) for the generated-handler host. The route in `app.ts` knows no provider; this
//! module maps each declared name to the handler trait's `runEvent`, delivers the declared payload
//! and answers with the handler's own emit of its `answers` event.

use crate::backend::*;

/// The statements at the top of a trait's HTTP handler that refuse an inbound hook event: only
/// `/api/hooks/<name>` delivers it (EXEC-INBOUND-1). Empty for a trait that handles none.
pub(crate) fn inbound_only_guard(module: &OirModule, trait_name: &str, framework: ServerFramework) -> String {
    let mut code = String::new();
    for route in module.inbound.iter().filter(|r| r.trait_name == trait_name) {
        let error = format!(
            "{trait_name}.{} is an inbound hook event: only /api/hooks/<name> delivers it",
            route.event
        );
        let rejection = format!(
            "{{ code: 'inbound-only-event', trait: '{trait_name}', event: '{}' }}",
            route.event
        );
        let response = format!(
            "{{ success: false, transitioned: false, states: {{}}, emittedEvents: [], error: {}, rejections: [{rejection}] }}",
            serde_json::to_string(&error).unwrap_or_default()
        );
        let send = match framework {
            ServerFramework::Express => format!("    res.status(403).json({response});\n    return;\n"),
            ServerFramework::Hono => format!("    return c.json({response}, 403);\n"),
        };
        code.push_str(&format!(
            "  if (body.event === {}) {{\n{send}  }}\n",
            serde_json::to_string(&route.event).unwrap_or_default()
        ));
    }
    code
}

impl TypeScriptBackend {
    pub(crate) fn generate_inbound_module(&self, module: &OirModule) -> InternalFile {
        let routes: Vec<&orbital_core_base::inbound::InboundRoute> = module
            .inbound
            .iter()
            .filter(|r| module.traits.iter().any(|t| t.name == r.trait_name))
            .collect();

        let mut code = String::new();
        code.push_str("/**\n * Inbound deliveries\n *\n");
        code.push_str(" * `/api/hooks/<name>` requests, delivered to the handler trait the program declares for the\n");
        code.push_str(" * name (`listens { EVENT -> inbound \"name\" answers ANSWER { … } }`). The route knows no\n");
        code.push_str(
            " * provider; the handler's transitions verify the sender and emit the answer (EXEC-INBOUND-1).\n",
        );
        code.push_str(" *\n * @generated by Orbital Compiler\n * @packageDocumentation\n */\n\n");

        if routes.is_empty() {
            code.push_str("import { unknownHook, type InboundAnswer, type InboundDelivery } from '@almadar/core';\n\n");
            code.push_str("export async function deliverInbound(name: string, _delivery: InboundDelivery): Promise<InboundAnswer> {\n");
            code.push_str("  return unknownHook(name);\n}\n");
            return InternalFile::new("packages/server/src/inbound.ts", code, GeneratedFileType::Route);
        }

        code.push_str("import { dispatchFailed, inboundAnswerOf, inboundPayload, unknownHook, type InboundAnswer, type InboundDelivery, type InboundRoute } from '@almadar/core';\n");
        code.push_str("import { resolveCredentialRef } from '@almadar/integrations';\n");
        code.push_str("import type { EventRequest, EventResponse } from '@app/shared';\n");
        code.push_str("import { broadcastBusEvent } from './sse.js';\n");
        for route in &routes {
            code.push_str(&format!(
                "import {{ runEvent as run{} }} from './routes/features/{}/handlers.js';\n",
                route.trait_name,
                to_kebab_case(&route.trait_name)
            ));
        }
        code.push_str("\ninterface InboundHandler {\n  route: InboundRoute;\n  run: (body: EventRequest) => Promise<EventResponse>;\n}\n\n");
        code.push_str("const HANDLERS: ReadonlyMap<string, InboundHandler> = new Map([\n");
        for route in &routes {
            let quoted = |s: &str| serde_json::to_string(s).unwrap_or_default();
            let verifies = route
                .verifies
                .as_ref()
                .map(|v| {
                    format!(
                        ", verifies: {{ header: {}, credential: {} }}",
                        quoted(&v.header),
                        quoted(&v.credential)
                    )
                })
                .unwrap_or_default();
            let route_json = format!(
                "{{ name: {}, orbital: {}, trait: {}, event: {}, answer: {}{} }}",
                quoted(&route.name),
                quoted(&route.orbital),
                quoted(&route.trait_name),
                quoted(&route.event),
                quoted(&route.answer),
                verifies
            );
            code.push_str(&format!(
                "  [{}, {{ route: {}, run: (body) => run{}(body, undefined) }}],\n",
                serde_json::to_string(&route.name).unwrap_or_default(),
                route_json,
                route.trait_name
            ));
        }
        code.push_str("]);\n\n");
        code.push_str(
            "export async function deliverInbound(name: string, delivery: InboundDelivery): Promise<InboundAnswer> {\n",
        );
        code.push_str("  const handler = HANDLERS.get(name);\n");
        code.push_str("  if (handler === undefined) return unknownHook(name);\n");
        code.push_str("  const { route } = handler;\n");
        code.push_str("  try {\n");
        code.push_str("    const credential = route.verifies !== undefined ? await resolveCredentialRef(route.verifies.credential, undefined, undefined) : undefined;\n");
        code.push_str("    const response = await handler.run({ event: route.event, payload: inboundPayload(route, delivery, credential) });\n");
        code.push_str("    for (const emitted of response.emittedEvents) {\n");
        code.push_str("      if (emitted.event === route.answer) continue;\n");
        code.push_str("      broadcastBusEvent(undefined, {\n");
        code.push_str("        type: 'bus',\n        event: emitted.event,\n        payload: emitted.payload,\n");
        code.push_str("        source: { orbital: route.orbital, trait: route.trait },\n        timestamp: Date.now(),\n      });\n");
        code.push_str("    }\n");
        code.push_str("    return inboundAnswerOf(route, response.emittedEvents, response.error);\n");
        code.push_str("  } catch (error) {\n");
        code.push_str("    return dispatchFailed(error instanceof Error ? error.message : String(error));\n");
        code.push_str("  }\n}\n");
        InternalFile::new("packages/server/src/inbound.ts", code, GeneratedFileType::Route)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use orbital_core_base::inbound::InboundRoute;

    fn module(routes: Vec<InboundRoute>, trait_names: &[&str]) -> OirModule {
        let mut module = OirModule::new("App", "1.0.0");
        module.inbound = routes;
        module.traits = trait_names.iter().map(|n| OirTrait::new(*n)).collect();
        module
    }

    fn route() -> InboundRoute {
        InboundRoute {
            name: "google-calendar".into(),
            orbital: "CalOrbital".into(),
            trait_name: "CalendarInbound".into(),
            event: "CALENDAR_PUSH".into(),
            answer: "CALENDAR_PUSH_ANSWERED".into(),
            verifies: Some(orbital_core_base::schema::InboundVerification {
                header: "x-goog-channel-token".into(),
                credential: "GOOGLE_CALENDAR_CHANNEL_TOKEN".into(),
            }),
        }
    }

    #[test]
    fn a_declared_handler_is_mapped_to_its_trait_runner_and_answers_with_its_own_emit() {
        let ts = TypeScriptBackend::default()
            .generate_inbound_module(&module(vec![route()], &["CalendarInbound"]))
            .content;
        assert!(
            ts.contains(
                "import { runEvent as runCalendarInbound } from './routes/features/calendar-inbound/handlers.js';"
            ),
            "{ts}"
        );
        assert!(ts.contains(r#"["google-calendar", { route: { name: "google-calendar", orbital: "CalOrbital", trait: "CalendarInbound", event: "CALENDAR_PUSH", answer: "CALENDAR_PUSH_ANSWERED", verifies: { header: "x-goog-channel-token", credential: "GOOGLE_CALENDAR_CHANNEL_TOKEN" } }, run: (body) => runCalendarInbound(body, undefined) }]"#), "{ts}");
        assert!(ts.contains("inboundPayload(route, delivery, credential)"), "{ts}");
        assert!(
            ts.contains("resolveCredentialRef(route.verifies.credential, undefined, undefined)"),
            "{ts}"
        );
        assert!(
            ts.contains("inboundAnswerOf(route, response.emittedEvents, response.error)"),
            "{ts}"
        );
        assert!(
            !ts.contains("google-calendar-hook") && !ts.contains("process.env"),
            "no provider or credential knowledge: {ts}"
        );
    }

    #[test]
    fn a_traits_http_handler_refuses_its_inbound_event_and_a_trait_without_one_is_untouched() {
        let m = module(vec![route()], &["CalendarInbound"]);
        let express = inbound_only_guard(&m, "CalendarInbound", ServerFramework::Express);
        assert!(express.contains("if (body.event === \"CALENDAR_PUSH\") {"), "{express}");
        assert!(express.contains("res.status(403).json("), "{express}");
        assert!(express.contains("code: 'inbound-only-event'"), "{express}");
        let hono = inbound_only_guard(&m, "CalendarInbound", ServerFramework::Hono);
        assert!(hono.contains("return c.json("), "{hono}");
        assert!(hono.contains(", 403);"), "{hono}");
        assert_eq!(inbound_only_guard(&m, "Other", ServerFramework::Express), "");
    }

    #[test]
    fn control_a_program_with_no_handler_serves_no_name() {
        let ts = TypeScriptBackend::default()
            .generate_inbound_module(&module(vec![], &["CalendarInbound"]))
            .content;
        assert!(ts.contains("return unknownHook(name);"), "{ts}");
        assert!(!ts.contains("HANDLERS") && !ts.contains("runEvent"), "{ts}");
        let orphan = TypeScriptBackend::default()
            .generate_inbound_module(&module(vec![route()], &["Other"]))
            .content;
        assert!(
            !orphan.contains("HANDLERS"),
            "a route whose trait is not in the module is not wired: {orphan}"
        );
    }
}
