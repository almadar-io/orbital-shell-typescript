use crate::backend::*;

impl TypeScriptBackend {
    /// Phase 7: Generate packages/server/src/eventListeners.ts (Express).
    ///
    /// Registers server-side cross-trait event listeners on the server event bus.
    /// When trait A emits an event, trait B's listener fires server-side for
    /// auditing, logging, and future real-time features (WebSocket broadcast).
    pub(crate) fn generate_server_event_listeners(&self, traits: &[OirTrait]) -> InternalFile {
        self.generate_server_event_listeners_impl(traits, ServerFramework::Express)
    }

    /// Shared implementation for both frameworks. The listener registration
    /// logic is framework-agnostic (it goes through `getServerEventBus()`,
    /// which both `@almadar/server` and `@almadar/server-hono` re-export with
    /// the same surface). Only the header banner, the import source, and the
    /// emitter-doc arrow glyph differ per framework, so they are switched on
    /// `framework` rather than copied into a parallel generator.
    pub(crate) fn generate_server_event_listeners_impl(
        &self,
        traits: &[OirTrait],
        framework: ServerFramework,
    ) -> InternalFile {
        let (banner, import_source, arrow) = match framework {
            ServerFramework::Express => ("Phase 7", "@almadar/server", "→"),
            ServerFramework::Hono => ("Hono backend", "@almadar/server-hono", "->"),
        };

        let mut code = String::new();

        code.push_str("/**\n * Server-Side Event Listeners\n *\n");
        code.push_str(" * Cross-trait event listeners registered on the server event bus.\n");
        code.push_str(" * When a trait emits an event, listeners here fire server-side for:\n");
        code.push_str(" * - Auditing and logging\n");
        code.push_str(" * - WebSocket broadcast to connected clients\n");
        code.push_str(" * - Future webhook/integration triggers\n");
        code.push_str(&format!(
            " *\n * @generated by Orbital Compiler ({})\n",
            banner
        ));
        code.push_str(" * @packageDocumentation\n */\n\n");

        code.push_str(&format!(
            "import {{ getServerEventBus, logger }} from '{}';\n\n",
            import_source
        ));

        // Collect all listener registrations across traits
        let mut has_listeners = false;
        let mut listener_registrations = String::new();

        for trait_def in traits {
            if trait_def.listeners.is_empty() {
                continue;
            }
            has_listeners = true;

            listener_registrations.push_str(&format!("  // {} trait listeners\n", trait_def.name));

            for listener in &trait_def.listeners {
                // Source-scoped server-side listener (Phase 9 follow-up). Same
                // shape as the compiled-shell React hook: register on the bare
                // event key; filter by `meta.source.{orbital,trait}` inside.
                let source_comment = match (&listener.source_orbital, &listener.source_trait) {
                    (Some(o), Some(t)) => format!(" (from {}.{})", o, t),
                    (None, Some(t)) => format!(" (from {})", t),
                    _ if listener.source_any => " (from *)".to_string(),
                    _ => String::new(),
                };
                // Source predicates now access `event.source?.{orbital,trait}`
                // from the `BusEvent` envelope delivered to every listener.
                let source_predicate = match (&listener.source_orbital, &listener.source_trait) {
                    (Some(orbital), Some(trait_name)) => format!(
                        "event.source?.orbital === '{}' && event.source?.trait === '{}'",
                        orbital, trait_name
                    ),
                    (None, Some(trait_name)) => format!("event.source?.trait === '{}'", trait_name),
                    _ => "true".to_string(),
                };

                listener_registrations.push_str(&format!(
                    "  getServerEventBus().on('{}', (event) => {{\n",
                    listener.event_pattern
                ));
                if source_predicate != "true" {
                    listener_registrations
                        .push_str(&format!("    if (!({})) return;\n", source_predicate));
                }
                listener_registrations.push_str(&format!(
                    "    logger.debug('[EventListener] {} received \\'{}\\'{}', event.payload);\n",
                    trait_def.name, listener.event_pattern, source_comment
                ));
                listener_registrations.push_str(&format!(
                    "    // Triggers '{}' on {} (client-side dispatch handles state machine transition)\n",
                    listener.triggers, trait_def.name
                ));
                // Traceability only — this file never dispatches, so the
                // refinement is applied at the client dispatch site.
                if listener.guard.is_some() {
                    listener_registrations
                        .push_str("    // when-guard applied client-side (payload-only scope)\n");
                }
                if let Some(mapping) = &listener.payload_mapping {
                    let mut keys: Vec<&String> = mapping.keys().collect();
                    keys.sort();
                    listener_registrations.push_str(&format!(
                        "    // with{{}} projection applied client-side — fields: {}\n",
                        keys.iter()
                            .map(|k| k.as_str())
                            .collect::<Vec<_>>()
                            .join(", ")
                    ));
                }
                listener_registrations.push_str("  });\n\n");
            }
        }

        // Build the emitter documentation
        let mut emitter_docs = String::new();
        for trait_def in traits {
            for trans in &trait_def.transitions {
                for effect_expr in &trans.effects {
                    if let OirExpr::Effect { effect } = effect_expr {
                        if let OirEffect::Emit { event, .. } = effect.as_ref() {
                            emitter_docs.push_str(&format!(
                                " *   {} emits '{}' (on {} {} {})\n",
                                trait_def.name, event, trans.event, arrow, trans.to
                            ));
                        }
                    }
                }
            }
        }

        if !emitter_docs.is_empty() {
            code.push_str("/**\n * Cross-trait event graph:\n *\n");
            code.push_str(" * Emitters:\n");
            code.push_str(&emitter_docs);
            code.push_str(" */\n\n");
        }

        code.push_str("/**\n * Register all server-side cross-trait event listeners.\n");
        code.push_str(" * Called once at server startup from registerRoutes().\n */\n");
        code.push_str("export function registerEventListeners(): void {\n");

        if has_listeners {
            code.push_str(&listener_registrations);
            // Count listeners for the log message
            let total_listeners: usize = traits.iter().map(|t| t.listeners.len()).sum();
            code.push_str(&format!(
                "  logger.info('[EventListener] Registered {} server-side cross-trait listener(s)');\n",
                total_listeners
            ));
        } else {
            code.push_str("  // No cross-trait listeners declared in schema\n");
        }

        code.push_str("}\n");

        InternalFile::new(
            "packages/server/src/eventListeners.ts",
            code,
            GeneratedFileType::Config,
        )
    }
}
