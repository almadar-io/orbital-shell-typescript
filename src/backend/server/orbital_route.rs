            assert!(js.contains("(merged.rejections ??= []).push({ code: 'no-dispatchable-traits', trait: seed.trait, event: seed.event });"), "{js}");
            // A seed whose effects throw is that seed's `effect-failed` rejection; the other seeds still run.
            assert!(js.contains("let r: EventResponse;\n    try {\n      r = await run({ ...base, event: seed.event, targetTrait: seed.trait }, user);\n    } catch (error) {"), "{js}");
