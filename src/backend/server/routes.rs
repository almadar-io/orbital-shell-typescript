use crate::backend::*;

impl TypeScriptBackend {
    pub(crate) fn generate_trait_event_handlers(
        &self,
        trait_def: &OirTrait,
        module: &OirModule,
    ) -> Vec<InternalFile> {
        let mut files = Vec::new();

        let trait_name = &trait_def.name;
        let folder_name = to_kebab_case(trait_name);

        files.push(self.generate_trait_event_handler_file(trait_def, module, &folder_name));
        files.push(self.generate_trait_event_routes(trait_def, &folder_name));
        files.push(self.generate_trait_event_index(trait_def, &folder_name));

        files
    }

    /// Generate Express routes for trait events
    pub(crate) fn generate_trait_event_routes(
        &self,
        trait_def: &OirTrait,
        folder_name: &str,
    ) -> InternalFile {
        let trait_name = &trait_def.name;

        let mut code = String::new();

        code.push_str(&format!("/**\n * {} Event Routes\n *\n", trait_name));
        code.push_str(" * Express router for trait event handling.\n");
        code.push_str(" * All operations go through POST /events endpoint.\n");
        code.push_str(" *\n * @packageDocumentation\n */\n\n");

        code.push_str("import { Router, type IRouter } from 'express';\n");
        code.push_str("import { handleEvent } from './handlers.js';\n\n");

        code.push_str("const router: IRouter = Router();\n\n");

        code.push_str("// All events go through this single endpoint\n");
        code.push_str("router.post('/events', handleEvent);\n\n");

        code.push_str("export default router;\n");

        InternalFile::new(
            format!(
                "packages/server/src/routes/features/{}/routes.ts",
                folder_name
            ),
            code,
            GeneratedFileType::Route,
        )
    }

    /// Generate index.ts barrel for trait event routes
    pub(crate) fn generate_trait_event_index(
        &self,
        _trait_def: &OirTrait,
        folder_name: &str,
    ) -> InternalFile {
        let code = "export { default as router } from './routes.js';\nexport { handleEvent } from './handlers.js';\n".to_string();

        InternalFile::new(
            format!(
                "packages/server/src/routes/features/{}/index.ts",
                folder_name
            ),
            code,
            GeneratedFileType::Barrel,
        )
    }

    /// Generate routes.ts registration for event-based routes (Express).
    pub(crate) fn generate_event_routes_registration(
        &self,
        traits: &[OirTrait],
        server_ticks: bool,
    ) -> InternalFile {
        self.generate_event_routes_registration_impl(traits, ServerFramework::Express, server_ticks)
    }

    /// Shared routes.ts registration for both frameworks. The trait-iteration
    /// structure is identical; only the framework primitives differ — Express
    /// imports each router as a default export and mounts via
    /// `app.use(path, router)` over `app: Express`, while Hono imports named
    /// router exports and mounts via `app.route(path, router)` over
    /// `app: Hono<AppEnv>` with a wildcard auth path. Switched on `framework`
    /// instead of maintained as a parallel generator.
    pub(crate) fn generate_event_routes_registration_impl(
        &self,
        traits: &[OirTrait],
        framework: ServerFramework,
        server_ticks: bool,
    ) -> InternalFile {
        let is_hono = framework == ServerFramework::Hono;

        let mut code = String::new();

        code.push_str("/**\n * Event Routes Registration\n *\n");
        code.push_str(" * Main routes file - registers all trait event routes.\n");
        code.push_str(
            " * All data operations flow through trait event handlers with guard enforcement.\n",
        );
        if is_hono {
            code.push_str(" *\n * @generated by Orbital Compiler (Hono backend)\n");
            code.push_str(" * @packageDocumentation\n */\n\n");
            code.push_str("import type { Hono } from 'hono';\n");
            code.push_str("import type { AppEnv } from '@almadar/server-hono';\n");
            code.push_str("import { identifyBearer } from '@almadar/server-hono';\n");
        } else {
            code.push_str(" *\n * @packageDocumentation\n */\n\n");
            code.push_str("import type { Express } from 'express';\n");
            code.push_str("import { identifyBearer } from '@almadar/server';\n");
        }
        code.push_str("import { registerEventListeners } from './eventListeners.js';\n");
        code.push_str("import { registerSseRoute } from './sse.js';\n");
        if server_ticks {
            code.push_str("import { startTicks } from './ticks.js';\n");
        }
        if is_hono {
            code.push_str("import { orbitalEventsRouter } from './routes/orbital-events.js';\n");
        } else {
            code.push_str("import orbitalEventsRouter from './routes/orbital-events.js';\n");
        }

        // Import routers — Hono uses named exports, Express default exports.
        for trait_def in traits {
            let folder_name = to_kebab_case(&trait_def.name);
            let var_name = format!("{}Router", to_camel_case(&trait_def.name));
            if is_hono {
                code.push_str(&format!(
                    "import {{ {} }} from './routes/features/{}/routes.js';\n",
                    var_name, folder_name
                ));
            } else {
                code.push_str(&format!(
                    "import {} from './routes/features/{}/routes.js';\n",
                    var_name, folder_name
                ));
            }
        }

        code.push_str(
            "\n/**\n * Register all trait event routes and server-side event listeners.\n *\n",
        );
        code.push_str(
            " * Every API request is identified by its verified bearer token, or is anonymous;\n",
        );
        code.push_str(" * the program's own guards decide what an anonymous visitor may do.\n");
        code.push_str(" * Cross-trait event listeners are wired via the server event bus.\n");
        code.push_str(" */\n");
        if is_hono {
            code.push_str("export function registerRoutes(app: Hono<AppEnv>): void {\n");
            code.push_str("  app.use('/api/*', identifyBearer);\n\n");
        } else {
            code.push_str("export function registerRoutes(app: Express): void {\n");
            code.push_str("  app.use('/api', identifyBearer);\n\n");
        }

        for trait_def in traits {
            let var_name = format!("{}Router", to_camel_case(&trait_def.name));
            let route_path = to_kebab_case(&trait_def.name);
            let mount = if is_hono { "route" } else { "use" };
            code.push_str(&format!(
                "  app.{}('/api/{}', {});\n",
                mount, route_path, var_name
            ));
        }

        code.push_str(
            "\n  // §156: orbital-scoped addressing — dispatches to the SAME per-trait handlers\n",
        );
        if is_hono {
            code.push_str("  app.route('/api/orbitals', orbitalEventsRouter);\n\n");
        } else {
            code.push_str("  app.use('/api/orbitals', orbitalEventsRouter);\n\n");
        }
        code.push_str(
            "\n  // Live-push: cross-client SSE broadcast of persist-effect success emits\n",
        );
        code.push_str("  registerSseRoute(app);\n\n");
        if server_ticks {
            code.push_str("  // Server trait ticks: mount-scoped unless `[background]` (Runtime Spec Clause 8).\n");
            code.push_str("  startTicks();\n\n");
        }
        code.push_str("  // Phase 7: Register server-side cross-trait event listeners\n");
        code.push_str("  registerEventListeners();\n");
        code.push_str("}\n");

        InternalFile::new(
            "packages/server/src/routes.ts",
            code,
            GeneratedFileType::Route,
        )
    }
}
