use crate::backend::*;

impl TypeScriptBackend {
    /// Generate seedMockData.ts based on schema entities (Express).
    pub(crate) fn generate_seed_mock_data(&self, entities: &[OirEntity]) -> InternalFile {
        self.generate_seed_mock_data_impl(entities, ServerFramework::Express)
    }

    /// Shared seedMockData.ts generator for both frameworks.
    ///
    /// The field-schema body (faker types, enum values, numeric defaults) and
    /// the instance-literal emission are framework-agnostic. Per-framework
    /// differences are switched on `framework`: the import source, the
    /// `seedData` row type, and the create-loop cast. The collection-name
    /// dedup (below) applies to both frameworks equally — a duplicate-key
    /// TS1117 from two entities resolving to the same `collection` is not
    /// framework-specific. Keeping the divergences explicit here lets a
    /// single field-emission change touch both backends.
    pub(crate) fn generate_seed_mock_data_impl(
        &self,
        entities: &[OirEntity],
        framework: ServerFramework,
    ) -> InternalFile {
        let mut code = String::new();

        code.push_str("/**\n * Mock Data Seeding\n *\n");
        code.push_str(" * Initializes mock data for development/testing.\n");
        code.push_str(" * Auto-generated from schema entities.\n");
        match framework {
            ServerFramework::Express => {
                code.push_str(" *\n * @generated by Orbital Compiler\n");
            }
            ServerFramework::Hono => {
                code.push_str(" *\n * @generated by Orbital Compiler (Hono backend)\n");
            }
        }
        code.push_str(" * @packageDocumentation\n */\n\n");

        let import_source = match framework {
            ServerFramework::Express => "@almadar/server",
            ServerFramework::Hono => "@almadar/server-hono",
        };
        code.push_str(&format!(
            "import {{ getMockDataService, type EntitySchema }} from '{}';\n",
            import_source
        ));
        code.push_str(&format!("import {{ logger }} from '{}';\n", import_source));
        code.push_str(&crate::codegen::handler_header::core_imports_clause(
            &["EntityPersistence", "EntityRow"].into_iter().collect(),
        ));
        if entities
            .iter()
            .flat_map(|e| &e.fields)
            .filter_map(|f| f.declared.as_ref())
            .any(|d| {
                seed_field_shape(d)
                    .pointer("/relation/entityId")
                    .is_some_and(|v| v.is_string())
            })
        {
            code.push_str("import { asEntityId } from '@almadar/core';\n");
        }
        let policy_consts: Vec<String> =
            crate::backend::server::access_policies::declared_policies(entities)
                .into_iter()
                .map(|(name, op)| {
                    crate::backend::server::access_policies::policy_const_name(&name, op)
                })
                .collect();
        if !policy_consts.is_empty() {
            code.push_str(&format!(
                "import {{ {} }} from './access-policies.js';\n",
                policy_consts.join(", ")
            ));
        }
        code.push('\n');

        // Seed rows are `EntityRow[]` (`{ id?: string } & Record<string,
        // FieldValue | undefined>` from @almadar/core) on both frameworks.
        code.push_str("interface SeedSchema extends EntitySchema {\n");
        code.push_str("  collection: string;\n");
        code.push_str("  name: string;\n");
        code.push_str("  persistence?: EntityPersistence;\n");
        code.push_str("  seedData?: EntityRow[];\n");
        code.push_str("}\n\n");

        // One entry per entity, in the shared seed order: the `[identity]` entity
        // first (its rows are the persona roster and the first draws of the seeded
        // stream), then declaration order — the order the runtime registers them in.
        // Entities sharing a collection each get an entry: the first seeds the
        // store, a later one backfills the fields it declares.
        code.push_str("const entitySchemas: SeedSchema[] = [\n");
        let ordered: Vec<&OirEntity> = entities
            .iter()
            .filter(|e| e.identity)
            .chain(entities.iter().filter(|e| !e.identity))
            .collect();

        for entity in ordered {
            code.push_str("  {\n");
            code.push_str(&format!(
                "    collection: '{}',\n",
                escape_js_string(&entity.collection)
            ));
            code.push_str(&format!(
                "    name: '{}',\n",
                escape_js_string(&entity.name)
            ));
            if entity.identity {
                // `[identity]` — these rows are the app's persona roster, served
                // by `personasRouter` and resolved against by `ALMADAR_PERSONA`.
                code.push_str("    identity: true,\n");
            }
            if entity.persistence == OirPersistence::Runtime {
                // A `[runtime]` singleton seeds ONE row at its declared defaults.
                code.push_str("    persistence: 'runtime',\n");
            }
            // The declared access directives: the seeder derives owner columns
            // and the `@create` owner gate from them with the same functions the
            // runtime uses (`ownerFieldsFromSchema`, `entityAccessPoliciesByStoreKey`).
            for (key, op, present) in [
                ("readPolicy", "READ", entity.read_policy.is_some()),
                ("createPolicy", "CREATE", entity.create_policy.is_some()),
                ("updatePolicy", "UPDATE", entity.update_policy.is_some()),
                ("deletePolicy", "DELETE", entity.delete_policy.is_some()),
            ] {
                if present {
                    code.push_str(&format!(
                        "    {}: {},\n",
                        key,
                        crate::backend::server::access_policies::policy_const_name(
                            &entity.name,
                            op
                        )
                    ));
                }
            }
            code.push_str("    fields: [\n");

            for field in &entity.fields {
                if let Some(declared) = &field.declared {
                    code.push_str(&format!(
                        "      {},\n",
                        seed_field_ts(&seed_field_shape(declared))
                    ));
                    continue;
                }
                let field_type = self.oir_type_to_mock_type(&field.field_type);
                let required = field.required;
                // `FieldSchema` is now the canonical `EntityField`, so EVERY
                // declared default is emitted — including `""`, which the
                // vocabulary-membership gate must be able to see, and including
                // arrays/objects, whose omission is what kept authored ui-*
                // content (`features = ["Item","Item 2"]`) out of generated apps.
                let mut extras = Vec::new();
                if let Some(ref values) = field.enum_values {
                    if !values.is_empty() {
                        let vals_str = values
                            .iter()
                            .map(|v| format!("'{}'", escape_js_string(v)))
                            .collect::<Vec<_>>()
                            .join(", ");
                        extras.push(format!("values: [{}]", vals_str));
                    }
                }
                if let Some(default) = field.default.as_ref() {
                    extras.push(format!("default: {}", oir_value_to_ts_literal(default)));
                }
                // `@intrinsic` — trait-owned frame/view-state, never a
                // persisted column. `@almadar/core`'s `sampleFieldValue`
                // already gates on this flag (never stamps random junk into
                // an intrinsic field, only the declared default); the flag
                // has to actually reach the generated `FieldSchema` literal
                // for that gate to see it.
                if field.intrinsic {
                    extras.push("intrinsic: true".to_string());
                }
                // A relation's TARGET was dropped here, so every emitted
                // `type: 'relation'` field arrived without the `relation` key
                // `RelationEntityField` requires. `MockDataService` looks the
                // target up to pick a real sibling id, found nothing, and seeded
                // `null` — so in a generated app EVERY entity-typed reference was
                // null and no ownership-scoped view could be non-empty, whatever
                // the viewer. Cardinality is mapped, not passed through: the TS
                // vocabulary is `one`/`many` (kebab for the paired forms) while
                // OIR's is camelCase, and only "one id or many" matters here.
                // The target is read from whichever source carries it: an
                // explicit `OirRelation`, else the `Reference` field type that
                // `oir_type_to_mock_type` already maps to `'relation'`. Keying
                // off only one of the two would leave the other emitting a bare
                // `type: 'relation'` again.
                let relation_target = field
                    .relation
                    .as_ref()
                    .map(|r| (r.target_entity.clone(), r.cardinality))
                    .or_else(|| match &field.field_type {
                        OirType::Reference { entity } => {
                            Some((entity.clone(), OirCardinality::ManyToOne))
                        }
                        _ => None,
                    });
                if let Some((target, cardinality)) = relation_target {
                    let cardinality = match cardinality {
                        OirCardinality::OneToOne | OirCardinality::ManyToOne => "one",
                        OirCardinality::OneToMany | OirCardinality::ManyToMany => "many",
                    };
                    extras.push(format!(
                        "relation: {{ entity: '{}', cardinality: '{}' }}",
                        escape_js_string(&target),
                        cardinality
                    ));
                }
                let extras_str = if extras.is_empty() {
                    String::new()
                } else {
                    format!(", {}", extras.join(", "))
                };
                code.push_str(&format!(
                    "      {{ name: '{}', type: '{}', required: {}{} }},\n",
                    field.name, field_type, required, extras_str
                ));
            }

            code.push_str("    ],\n");

            if !entity.instances.is_empty() {
                // Emit actual instance data
                code.push_str("    seedData: [\n");
                for instance in &entity.instances {
                    code.push_str("      { ");
                    let mut first = true;
                    for (key, value) in instance {
                        if !first {
                            code.push_str(", ");
                        }
                        code.push_str(&format!(
                            "{}: {}",
                            crate::codegen::ts_ident::ts_member_name(key),
                            self.oir_value_to_ts(value)
                        ));
                        first = false;
                    }
                    code.push_str(" },\n");
                }
                code.push_str("    ],\n");
            } else if entity.persistence == OirPersistence::Runtime {
                code.push_str("    seedCount: 1,\n");
            } else {
                code.push_str("    seedCount: 6,\n");
            }

            code.push_str("  },\n");
        }

        code.push_str("];\n\n");

        code.push_str("/**\n * Initialize mock data for all entities\n */\n");
        code.push_str("export async function initializeMockData(): Promise<void> {\n");
        code.push_str("  for (const schema of entitySchemas) {\n");
        code.push_str("    getMockDataService().registerSchema(schema.collection, schema);\n");
        code.push_str("    if (schema.seedData) {\n");
        code.push_str("      // Authored instances, created as-is (the mock store mints ids and timestamps they omit).\n");
        code.push_str(
            "      for (const item of schema.seedData) { getMockDataService().create(schema.name, item as Partial<{ id: string; createdAt: string; updatedAt: string }>); }\n",
        );
        code.push_str(
            "      logger.info(`Seeded ${schema.seedData.length} ${schema.name} (from schema instances)`);\n",
        );
        code.push_str("    } else {\n");
        code.push_str(
            "      getMockDataService().seed(schema.name, schema.fields, schema.seedCount ?? 6, schema.persistence);\n",
        );
        code.push_str("    }\n");
        code.push_str("  }\n");
        code.push_str("}\n");

        InternalFile::new(
            "packages/server/src/seedMockData.ts",
            code,
            GeneratedFileType::Config,
        )
    }

    /// Phase F.5 test hook: emit the seedMockData.ts content for a given
    /// entity slice without exposing the private `InternalFile` type. This
    /// lets `tests/mock_default_completeness.rs` lock in the literal-default
    /// emission rules without making the codegen function itself public.
    pub fn render_seed_mock_data_content(&self, entities: &[OirEntity]) -> String {
        self.generate_seed_mock_data(entities).content
    }
}

/// The declared field as the mock seeder reads it: exactly the `.orb` keys
/// `sampleFieldValue` consults, recursively through `items` / `properties`, so the
/// compiled app samples the same shape the runtime does.
fn seed_field_shape(declared: &serde_json::Value) -> serde_json::Value {
    const KEYS: [&str; 7] = [
        "name",
        "type",
        "required",
        "default",
        "values",
        "intrinsic",
        "mock",
    ];
    let Some(obj) = declared.as_object() else {
        return declared.clone();
    };
    let mut out = serde_json::Map::new();
    for key in KEYS {
        if let Some(v) = obj.get(key) {
            out.insert(key.to_string(), v.clone());
        }
    }
    if let Some(rel) = obj.get("relation").and_then(|r| r.as_object()) {
        let mut relation = serde_json::Map::new();
        for key in ["entity", "entityId", "cardinality"] {
            if let Some(v) = rel.get(key) {
                relation.insert(key.to_string(), v.clone());
            }
        }
        out.insert("relation".to_string(), serde_json::Value::Object(relation));
    }
    if let Some(items) = obj.get("items") {
        out.insert("items".to_string(), seed_field_shape(items));
    }
    if let Some(props) = obj.get("properties").and_then(|p| p.as_object()) {
        let mut sorted: Vec<(&String, &serde_json::Value)> = props.iter().collect();
        sorted.sort_by(|a, b| a.0.cmp(b.0));
        let shaped: serde_json::Map<String, serde_json::Value> = sorted
            .into_iter()
            .map(|(k, v)| (k.clone(), seed_field_shape(v)))
            .collect();
        out.insert("properties".to_string(), serde_json::Value::Object(shaped));
    }
    serde_json::Value::Object(out)
}

/// A seed field shape as a TypeScript literal: JSON, except a relation's
/// `entityId`, which `@almadar/core` types as the branded `EntityId` and so goes
/// through its prefix-checked `asEntityId` (G-ORB-028).
fn seed_field_ts(shape: &serde_json::Value) -> String {
    fn emit(value: &serde_json::Value, in_relation: bool) -> String {
        match value {
            serde_json::Value::Object(map) => {
                let parts: Vec<String> = map
                    .iter()
                    .map(|(k, v)| {
                        let key = serde_json::to_string(k).unwrap_or_default();
                        let rendered = match v {
                            serde_json::Value::String(id) if in_relation && k == "entityId" => {
                                format!(
                                    "asEntityId({})",
                                    serde_json::to_string(id).unwrap_or_default()
                                )
                            }
                            _ => emit(v, k == "relation"),
                        };
                        format!("{key}:{rendered}")
                    })
                    .collect();
                format!("{{{}}}", parts.join(","))
            }
            serde_json::Value::Array(items) => {
                format!(
                    "[{}]",
                    items
                        .iter()
                        .map(|v| emit(v, false))
                        .collect::<Vec<_>>()
                        .join(",")
                )
            }
            other => other.to_string(),
        }
    }
    emit(shape, false)
}

#[cfg(test)]
mod intrinsic_field_seed_tests {
    use super::*;
    use orbital_core::ir::OirField;

    fn entity_with_intrinsic_field() -> OirEntity {
        let mut draft_field = OirField::new("draft", OirType::String);
        draft_field.required = false;
        draft_field.intrinsic = true;
        OirEntity {
            shared: false,
            identity: false,
            local: false,
            seed_mock: false,
            id: None,
            name: "Note".to_string(),
            description: None,
            collection: "notes".to_string(),
            persistence: OirPersistence::Persistent,
            fields: vec![
                OirField::new("id", OirType::String),
                OirField::new("title", OirType::String),
                draft_field,
            ],
            defaults: None,
            instances: vec![],
            used_by_traits: vec![],
            used_by_pages: vec![],
            read_policy: None,
            create_policy: None,
            update_policy: None,
            delete_policy: None,
        }
    }

    /// §88: the seeded `FieldSchema` literal must carry `intrinsic: true` for
    /// an `@intrinsic` field — `@almadar/core`'s `sampleFieldValue` already
    /// gates on this flag (never stamps a random value into an intrinsic
    /// field), but only if the generated schema actually sets it.
    #[test]
    fn express_and_hono_seed_mark_intrinsic_fields() {
        let backend = TypeScriptBackend::new();
        let entities = vec![entity_with_intrinsic_field()];

        let express = backend.generate_seed_mock_data(&entities).content;
        let hono = backend
            .generate_seed_mock_data_impl(&entities, ServerFramework::Hono)
            .content;

        for (name, ts) in [("Express", &express), ("Hono", &hono)] {
            assert!(
                ts.contains("{ name: 'draft', type: 'string', required: false, intrinsic: true },"),
                "{name} seed schema must mark the intrinsic field, got:\n{ts}"
            );
            assert!(
                !ts.contains("{ name: 'title', type: 'string', required: true, intrinsic: true }"),
                "{name} seed schema must not mark a non-intrinsic field intrinsic, got:\n{ts}"
            );
        }
    }
}

#[cfg(test)]
mod relation_entity_id_seed_tests {
    //! G-ORB-028: a relation's `entityId` is `@almadar/core`'s branded
    //! `EntityId`; the seed literal must brand it (`asEntityId`, prefix-checked)
    //! or the generated server fails `tsc` (std-hr-portal OrgNode.managerId).
    use super::*;
    use orbital_core::ir::OirField;

    fn org_node(entity_id: Option<&str>) -> OirEntity {
        let mut manager = OirField::new("managerId", OirType::String);
        let mut relation = serde_json::json!({ "entity": "OrgNode", "cardinality": "one" });
        if let Some(id) = entity_id {
            relation["entityId"] = serde_json::json!(id);
        }
        manager.declared = Some(
            serde_json::json!({ "name": "managerId", "type": "relation", "relation": relation }),
        );
        OirEntity {
            shared: false,
            identity: false,
            local: false,
            seed_mock: false,
            id: None,
            name: "OrgNode".to_string(),
            description: None,
            collection: "orgnodes".to_string(),
            persistence: OirPersistence::Persistent,
            fields: vec![OirField::new("id", OirType::String), manager],
            defaults: None,
            instances: vec![],
            used_by_traits: vec![],
            used_by_pages: vec![],
            read_policy: None,
            create_policy: None,
            update_policy: None,
            delete_policy: None,
        }
    }

    #[test]
    fn a_relation_entity_id_is_branded_and_imported() {
        let ts = TypeScriptBackend::new()
            .generate_seed_mock_data(&[org_node(Some("ent_01ABC"))])
            .content;
        assert!(ts.contains(r#""entityId":asEntityId("ent_01ABC")"#), "{ts}");
        assert!(ts.contains("asEntityId"), "{ts}");
        assert!(
            ts.lines().any(|l| l.starts_with("import")
                && l.contains("asEntityId")
                && l.contains("@almadar/core")),
            "{ts}"
        );
    }

    #[test]
    fn control_a_relation_without_an_id_imports_nothing_extra() {
        let ts = TypeScriptBackend::new()
            .generate_seed_mock_data(&[org_node(None)])
            .content;
        assert!(!ts.contains("asEntityId"), "{ts}");
    }
}
