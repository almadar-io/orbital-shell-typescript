use crate::backend::server::access_policies::policy_const_name;
use crate::backend::*;

impl TypeScriptBackend {
    /// Generate `packages/server/src/sse.ts` (Express).
    pub(crate) fn generate_sse_module(
        &self,
        entities: &[OirEntity],
        server_ticks: bool,
    ) -> InternalFile {
        self.generate_sse_module_impl(entities, ServerFramework::Express, server_ticks)
    }

    /// Generate `packages/server/src/sse.ts` (Hono).
    pub(crate) fn generate_sse_module_hono(
        &self,
        entities: &[OirEntity],
        server_ticks: bool,
    ) -> InternalFile {
        self.generate_sse_module_impl(entities, ServerFramework::Hono, server_ticks)
    }

    /// Shared SSE broadcast channel for both frameworks — see
    /// `Almadar_Live_Push.md`. A persist effect's `emit:{success}` envelope
    /// (the ONLY effect class this fires for — see the positional call sites
    /// in `codegen/effect/persist.rs`) is broadcast here to every OTHER
    /// connected client, so the closed-circuit `listens -> INIT -> (fetch
    /// ...)` idiom fires cross-client, not just in-response to the origin
    /// request. Origin exclusion is by `clientId` (the response already
    /// delivered the emit to its own dispatcher).
    ///
    /// §88: a connection also stores the viewer's `UserContext`. When the
    /// broadcast item names an entity (`entityType`, stamped by the emitting
    /// persist effect) that declares an `@read` policy, `broadcastBusEvent`
    /// runs `applyRowAccess` per connection and skips one whose viewer can't
    /// see the row — without this, EVERY persisted row reached EVERY open
    /// tab regardless of who was allowed to read it, the read-side hole a
    /// declared `@read` closes on the request/response path already.
    ///
    /// Express holds the raw `Response` per connection and writes SSE frames
    /// directly; Hono has no raw `Response` handle under `@hono/node-server`,
    /// so it holds `hono/streaming`'s `SSEStreamingApi` instead and writes
    /// through `writeSSE`. Both frameworks keep the connection open until the
    /// client disconnects and clean up the registry entry on close/abort.
    pub(crate) fn generate_sse_module_impl(
        &self,
        entities: &[OirEntity],
        framework: ServerFramework,
        server_ticks: bool,
    ) -> InternalFile {
        let mut code = String::new();
        // Only entities with a declared `@read` need anything here — an
        // import from `./access-policies.js` when the module declares NO
        // policy at all would be a module-not-found (`generate_access_policies`
        // emits no file in that case), so this list also gates the import.
        let read_policied: Vec<(&str, String)> = entities
            .iter()
            .filter(|e| e.read_policy.is_some())
            .map(|e| (e.name.as_str(), policy_const_name(&e.name, "READ")))
            .collect();

        code.push_str("/**\n * Live-push SSE channel\n *\n");
        code.push_str(
            " * Broadcasts a persist effect's `emit:{success}` envelope to every OTHER\n",
        );
        code.push_str(
            " * connected client so the closed-circuit `listens -> INIT -> (fetch ...)`\n",
        );
        code.push_str(" * idiom fires cross-client (see Almadar_Live_Push.md).\n *\n");
        match framework {
            ServerFramework::Express => code.push_str(" * @generated by Orbital Compiler\n"),
            ServerFramework::Hono => {
                code.push_str(" * @generated by Orbital Compiler (Hono backend)\n")
            }
        }
        code.push_str(" * @packageDocumentation\n */\n\n");

        match framework {
            ServerFramework::Express => {
                code.push_str("import type { Express, Request, Response } from 'express';\n");
                code.push_str("import { mintStreamTicket, requireStreamTicket } from '@almadar/server';\n");
            }
            ServerFramework::Hono => {
                code.push_str("import type { Hono } from 'hono';\n");
                code.push_str(
                    "import { streamSSE, type SSEStreamingApi } from 'hono/streaming';\n",
                );
                code.push_str("import type { AppEnv } from '@almadar/server-hono';\n");
                code.push_str("import { mintStreamTicket, requireStreamTicket } from '@almadar/server-hono';\n");
            }
        }
        code.push_str("import { StreamTicketStore } from '@almadar/auth/server';\n");
        code.push_str("import type { BusBroadcastItem, DispatchPushItem } from '@app/shared';\n");
        if server_ticks {
            code.push_str("import { releaseClient } from './mounts.js';\n");
        }
        // A tab's last connection closing unmounts its traits (Runtime Spec Clause 8.3).
        let release = if server_ticks {
            "if (clientId !== undefined && ![...connections].some((c) => c.clientId === clientId)) releaseClient(clientId);"
        } else {
            ""
        };
        code.push_str(&crate::codegen::handler_header::core_imports_clause(
            &["UserContext"].into_iter().collect(),
        ));
        code.push_str("import { viewerOf } from './viewer.js';\n");
        if !read_policied.is_empty() {
            code.push_str(&crate::codegen::handler_header::core_imports_clause(
                &["SExpr", "EntityRow", "EventPayloadValue"]
                    .into_iter()
                    .collect(),
            ));
            code.push_str("import { applyRowAccess } from '@almadar/evaluator/entityAccess';\n");
            let policy_names: Vec<&str> = read_policied.iter().map(|(_, c)| c.as_str()).collect();
            code.push_str(&format!(
                "import {{ {} }} from './access-policies.js';\n",
                policy_names.join(", ")
            ));
        }
        code.push('\n');

        if !read_policied.is_empty() {
            code.push_str(crate::codegen::handler_header::TO_ENTITY_ROW_DECL);
            code.push('\n');
            code.push_str(
                "/** Entity name -> its declared `@read` policy, for `broadcastBusEvent`'s\n",
            );
            code.push_str(" * per-connection scoping below. */\n");
            code.push_str("const READ_POLICY_BY_ENTITY: Record<string, SExpr> = {\n");
            for (entity_name, policy_const) in &read_policied {
                code.push_str(&format!("  '{}': {},\n", entity_name, policy_const));
            }
            code.push_str("};\n\n");
        }

        code.push_str("interface SseConnection {\n");
        match framework {
            ServerFramework::Express => code.push_str("  res: Response;\n"),
            ServerFramework::Hono => code.push_str("  stream: SSEStreamingApi;\n"),
        }
        code.push_str("  clientId?: string;\n");
        code.push_str("  user?: UserContext;\n");
        code.push_str("}\n\n");

        code.push_str("const connections = new Set<SseConnection>();\n\n");
        code.push_str("/** Single-use tickets that open the stream: an `EventSource` sends no header, and a token in the URL leaks into logs. */\n");
        code.push_str("const streamTickets = new StreamTicketStore();\n\n");

        code.push_str("/** Write `item` to every connected client except the one whose\n");
        code.push_str(" * `clientId` equals `originClientId` — that client already received\n");
        code.push_str(
            " * the emit in-response; a second delivery would double-fire its `listens`.\n",
        );
        code.push_str(" */\n");
        code.push_str(
            "export function broadcastBusEvent(originClientId: string | undefined, item: BusBroadcastItem): void {\n",
        );
        // `item.entityType` is set ONLY on a persist effect's broadcast
        // (`emit_success_js_impl`); a plain `(emit X)` never carries one, so
        // this whole block is skipped for it. Fails OPEN (delivers) when the
        // payload isn't row-shaped — every persist-success broadcast this
        // codegen emits always carries the persisted row as `payload`, so
        // that branch is structurally unreachable, not a policy decision.
        let visibility_check = if read_policied.is_empty() {
            String::new()
        } else {
            "    if (item.entityType !== undefined) {\n      \
             const policy = READ_POLICY_BY_ENTITY[item.entityType];\n      \
             if (policy !== undefined) {\n        \
             const row = __toEntityRow(item.payload);\n        \
             if (row !== undefined && applyRowAccess([row], policy, undefined, { user: conn.user, now }).length === 0) continue;\n      \
             }\n    \
             }\n"
                .to_string()
        };
        if !read_policied.is_empty() {
            code.push_str("  const now = Date.now();\n");
        }
        match framework {
            ServerFramework::Express => {
                code.push_str("  const frame = `data: ${JSON.stringify(item)}\\n\\n`;\n");
                code.push_str("  for (const conn of connections) {\n");
                code.push_str(
                    "    if (conn.clientId !== undefined && conn.clientId === originClientId) continue;\n",
                );
                code.push_str(&visibility_check);
                code.push_str("    conn.res.write(frame);\n");
                code.push_str("  }\n");
            }
            ServerFramework::Hono => {
                code.push_str("  for (const conn of connections) {\n");
                code.push_str(
                    "    if (conn.clientId !== undefined && conn.clientId === originClientId) continue;\n",
                );
                code.push_str(&visibility_check);
                code.push_str("    void conn.stream.writeSSE({ data: JSON.stringify(item) });\n");
                code.push_str("  }\n");
            }
        }
        code.push_str("}\n\n");

        code.push_str("/** Write `item` only to the requesting tab's connections: a running\n");
        code.push_str(" * call's live message (`emit.onMessage`), delivered while it runs. */\n");
        code.push_str(
            "export function pushToOrigin(originClientId: string | undefined, item: BusBroadcastItem | DispatchPushItem): void {\n",
        );
        code.push_str("  if (originClientId === undefined) return;\n");
        match framework {
            ServerFramework::Express => {
                code.push_str("  const frame = `data: ${JSON.stringify(item)}\\n\\n`;\n");
                code.push_str("  for (const conn of connections) {\n");
                code.push_str("    if (conn.clientId === originClientId) conn.res.write(frame);\n");
                code.push_str("  }\n");
            }
            ServerFramework::Hono => {
                code.push_str("  for (const conn of connections) {\n");
                code.push_str("    if (conn.clientId === originClientId) void conn.stream.writeSSE({ data: JSON.stringify(item) });\n");
                code.push_str("  }\n");
            }
        }
        code.push_str("}\n\n");

        match framework {
            ServerFramework::Express => {
                code.push_str("export function registerSseRoute(app: Express): void {\n");
                code.push_str("  app.post('/api/events/ticket', mintStreamTicket(streamTickets));\n");
                code.push_str(
                    "  app.get('/api/events', requireStreamTicket(streamTickets), async (req: Request, res: Response) => {\n",
                );
                code.push_str(
                    "    const clientId = typeof req.query.clientId === 'string' ? req.query.clientId : undefined;\n",
                );
                code.push_str("    res.set({\n");
                code.push_str("      'Content-Type': 'text/event-stream',\n");
                code.push_str("      'Cache-Control': 'no-cache',\n");
                code.push_str("      Connection: 'keep-alive',\n");
                code.push_str("    });\n");
                code.push_str("    res.flushHeaders();\n");
                code.push_str("    const user: UserContext = await viewerOf(req.authUser);\n");
                code.push_str("    const conn: SseConnection = { res, clientId, user };\n");
                code.push_str("    connections.add(conn);\n");
                code.push_str("    req.on('close', () => {\n");
                code.push_str("      connections.delete(conn);\n");
                if server_ticks {
                    code.push_str(&format!("      {release}\n"));
                }
                code.push_str("    });\n");
                code.push_str("  });\n");
                code.push_str("}\n");
            }
            ServerFramework::Hono => {
                code.push_str("export function registerSseRoute(app: Hono<AppEnv>): void {\n");
                code.push_str("  app.post('/api/events/ticket', mintStreamTicket(streamTickets));\n");
                code.push_str("  app.get('/api/events', requireStreamTicket(streamTickets), async (c) => {\n");
                code.push_str("    const clientId = c.req.query('clientId');\n");
                code.push_str("    const user: UserContext = await viewerOf(c.get('authUser'));\n");
                code.push_str("    return streamSSE(c, async (stream) => {\n");
                code.push_str("      const conn: SseConnection = { stream, clientId, user };\n");
                code.push_str("      connections.add(conn);\n");
                code.push_str("      await new Promise<void>((resolve) => {\n");
                code.push_str("        stream.onAbort(() => {\n");
                code.push_str("          connections.delete(conn);\n");
                if server_ticks {
                    code.push_str(&format!("          {release}\n"));
                }
                code.push_str("          resolve();\n");
                code.push_str("        });\n");
                code.push_str("      });\n");
                code.push_str("    });\n");
                code.push_str("  });\n");
                code.push_str("}\n");
            }
        }

        InternalFile::new("packages/server/src/sse.ts", code, GeneratedFileType::Route)
    }
}
