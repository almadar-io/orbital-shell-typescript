use crate::backend::*;

impl TypeScriptBackend {
    /// Generate `packages/server/src/viewer.ts`: the one place a verified token becomes `@user`.
    ///
    /// The identity source is fixed here from the program's `[identity]` entity, the same entity
    /// the seeder orders first: `[persistent, identity]` reads the row keyed by the verified uid
    /// through the data service, `[runtime, identity]` reads its declared fields from the token's
    /// claims, and no identity entity reads the token itself. `identityRoster()` lists the rows
    /// the dev persona sign-in (`personasRouter`) offers.
    pub(crate) fn generate_viewer_module(
        &self,
        entities: &[OirEntity],
        framework: ServerFramework,
    ) -> InternalFile {
        InternalFile::new(
            "packages/server/src/viewer.ts",
            render_viewer_module(entities, framework),
            GeneratedFileType::Config,
        )
    }
}

pub(crate) fn render_viewer_module(entities: &[OirEntity], framework: ServerFramework) -> String {
    let server = match framework {
        ServerFramework::Express => "@almadar/server",
        ServerFramework::Hono => "@almadar/server-hono",
    };
    let identity = entities.iter().find(|e| e.identity);
    let mut code = String::new();
    code.push_str("/**\n * The request viewer: a verified token resolved to `@user` against the app's `[identity]` entity.\n *\n");
    code.push_str(" * @generated by Orbital Compiler\n * @packageDocumentation\n */\n\n");
    code.push_str(
        "import { resolveViewer, type IdentitySource, type VerifiedUser } from '@almadar/auth';\n",
    );
    match identity {
        Some(entity) if entity.persistence != OirPersistence::Runtime => {
            code.push_str("import { personaFromIdentityRow, type EntityRow, type UserContext } from '@almadar/core';\n");
            code.push_str(&format!("import {{ getDataService }} from '{server}';\n\n"));
            code.push_str(&format!(
                "const IDENTITY: IdentitySource = {{ kind: 'directory', entity: '{}' }};\n",
                escape_js_string(&entity.name)
            ));
            code.push_str(&format!(
                "const IDENTITY_COLLECTION = '{}';\n\n",
                escape_js_string(&entity.collection)
            ));
            code.push_str("const identityLookup = {\n");
            code.push_str("  getById: (_entity: string, id: string): Promise<EntityRow | null> => getDataService().getById<EntityRow>(IDENTITY_COLLECTION, id),\n");
            code.push_str("};\n\n");
            code.push_str("export function viewerOf(verified: VerifiedUser | undefined): Promise<UserContext> {\n");
            code.push_str("  return resolveViewer(verified ?? null, IDENTITY, identityLookup);\n");
            code.push_str("}\n\n");
            code.push_str("export async function identityRoster(): Promise<UserContext[]> {\n");
            code.push_str(
                "  const rows = await getDataService().list<EntityRow>(IDENTITY_COLLECTION);\n",
            );
            code.push_str("  return rows.flatMap((row) => {\n");
            code.push_str("    const persona = personaFromIdentityRow(row);\n");
            code.push_str("    return persona ? [persona] : [];\n");
            code.push_str("  });\n");
            code.push_str("}\n");
        }
        Some(entity) => {
            let fields: Vec<String> = entity
                .fields
                .iter()
                .map(|f| format!("'{}'", escape_js_string(&f.name)))
                .collect();
            code.push_str("import type { UserContext } from '@almadar/core';\n\n");
            code.push_str(&format!(
                "const IDENTITY: IdentitySource = {{ kind: 'claims', fields: [{}] }};\n\n",
                fields.join(", ")
            ));
            code.push_str("export function viewerOf(verified: VerifiedUser | undefined): Promise<UserContext> {\n");
            code.push_str("  return resolveViewer(verified ?? null, IDENTITY);\n");
            code.push_str("}\n\n");
            code.push_str("/** A `[runtime, identity]` viewer comes from the provider; there are no rows to sign in as. */\n");
            code.push_str("export async function identityRoster(): Promise<UserContext[]> {\n");
            code.push_str("  return [];\n");
            code.push_str("}\n");
        }
        None => {
            code.push_str("import type { UserContext } from '@almadar/core';\n\n");
            code.push_str("const IDENTITY: IdentitySource = { kind: 'none' };\n\n");
            code.push_str("export function viewerOf(verified: VerifiedUser | undefined): Promise<UserContext> {\n");
            code.push_str("  return resolveViewer(verified ?? null, IDENTITY);\n");
            code.push_str("}\n\n");
            code.push_str("/** The app declares no `[identity]` entity, so there are no personas to sign in as. */\n");
            code.push_str("export async function identityRoster(): Promise<UserContext[]> {\n");
            code.push_str("  return [];\n");
            code.push_str("}\n");
        }
    }
    code
}

#[cfg(test)]
mod tests {
    use super::*;
    use orbital_core_base::ir::OirField;

    fn entity(
        name: &str,
        collection: &str,
        identity: bool,
        persistence: OirPersistence,
    ) -> OirEntity {
        OirEntity {
            shared: false,
            identity,
            local: false,
            seed_mock: false,
            id: None,
            name: name.to_string(),
            description: None,
            collection: collection.to_string(),
            persistence,
            fields: vec![
                OirField::new("id", OirType::String),
                OirField::new("role", OirType::String),
            ],
            defaults: None,
            instances: vec![],
            used_by_traits: vec![],
            used_by_pages: vec![],
            read_policy: None,
            create_policy: None,
            update_policy: None,
            delete_policy: None,
        }
    }

    #[test]
    fn a_persistent_identity_entity_is_a_directory_read_through_its_collection() {
        let entities = vec![
            entity("Task", "tasks", false, OirPersistence::Persistent),
            entity("Member", "members", true, OirPersistence::Persistent),
        ];
        for framework in [ServerFramework::Express, ServerFramework::Hono] {
            let ts = render_viewer_module(&entities, framework);
            assert!(
                ts.contains(
                    "const IDENTITY: IdentitySource = { kind: 'directory', entity: 'Member' };"
                ),
                "{ts}"
            );
            assert!(
                ts.contains("const IDENTITY_COLLECTION = 'members';"),
                "{ts}"
            );
            assert!(
                ts.contains("return resolveViewer(verified ?? null, IDENTITY, identityLookup);"),
                "{ts}"
            );
            assert!(
                ts.contains("getDataService().list<EntityRow>(IDENTITY_COLLECTION)"),
                "{ts}"
            );
        }
        assert!(render_viewer_module(&entities, ServerFramework::Hono)
            .contains("from '@almadar/server-hono'"));
        assert!(render_viewer_module(&entities, ServerFramework::Express)
            .contains("from '@almadar/server'"));
    }

    #[test]
    fn a_runtime_identity_entity_reads_its_declared_fields_from_claims() {
        let entities = vec![entity("Viewer", "viewers", true, OirPersistence::Runtime)];
        let ts = render_viewer_module(&entities, ServerFramework::Express);
        assert!(
            ts.contains(
                "const IDENTITY: IdentitySource = { kind: 'claims', fields: ['id', 'role'] };"
            ),
            "{ts}"
        );
        assert!(!ts.contains("getDataService"), "{ts}");
    }

    #[test]
    fn control_no_identity_entity_reads_the_token_and_has_no_roster() {
        let entities = vec![entity("Task", "tasks", false, OirPersistence::Persistent)];
        let ts = render_viewer_module(&entities, ServerFramework::Express);
        assert!(
            ts.contains("const IDENTITY: IdentitySource = { kind: 'none' };"),
            "{ts}"
        );
        assert!(ts.contains("return [];"), "{ts}");
        assert!(!ts.contains("getDataService"), "{ts}");
    }
}
