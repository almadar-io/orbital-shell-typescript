    /// Generate a Zod schema expression for an event's payload.
    ///
    /// Returns something like `z.object({ name: z.string(), amount: z.number() })`.
    /// Uses the shared `map_type_to_zod_with_refs` with `ZodRefMode::IdString`
    /// (a payload reference field is just a string id — no entity `XSchema` is
    /// imported at this inline per-event validation site).
    fn generate_payload_zod_schema(&self, event: &OirEvent) -> String {
        if let Some(schema) = &event.payload_schema {
            if !schema.is_empty() {
                let mut fields: Vec<String> = schema
                    .iter()
                    .map(|(name, oir_type)| {
                        format!(
                            "  {}: {}",
                            name,
                            self.map_type_to_zod_with_refs(oir_type, None, ZodRefMode::IdString)
                        )
                    })
                    .collect();
                fields.sort(); // deterministic output
                return format!("z.object({{\n{}\n}})", fields.join(",\n"));
            }
        }
        "z.object({})".to_string()
    }

