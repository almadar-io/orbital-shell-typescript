//! Service Client Code Generation
//!
//! Generates the server's `services/clients.ts`: the declared and invoked service names the boot check reads, and the
//! tenant credential store install and the credentials the app declares. `call-service` itself is a kernel ask the kernel host answers, so no client is emitted.

use orbital_core_base::ir::OirModule;
use orbital_core_base::schema::{ServiceDefinition, ServiceRef};
use orbital_core_base::secrets::ProgramCredential;
use std::collections::BTreeSet;

/// Generate the server's `services/clients.ts`.
pub fn generate_service_clients(
    services: &[ServiceRef],
    invoked: &BTreeSet<String>,
    program_credentials: &[ProgramCredential],
) -> String {
    let mut ts = String::new();

    ts.push_str("/**\n");
    ts.push_str(" * Service Clients - Generated by Orbital Compiler\n");
    ts.push_str(" *\n");
    ts.push_str(" * The kernel host answers every `call-service`; this module names the services\n");
    ts.push_str(" * and installs the tenant credential store.\n");
    ts.push_str(" */\n\n");

    ts.push_str("import {\n  CredentialStore,\n  credentialsFromStoreOnly,\n  installCredentialStore,\n  seedCredentialStore,\n  type CredentialPersistence,\n} from '@almadar/runtime/credentials';\nimport { loadInstalledKernel } from '@almadar/runtime/kernelNode';\n\n");

    let declared = declared_credentials(invoked, program_credentials);
    ts.push_str("/** The credentials this app declares (the registry's for its invoked services, then its own `secret` knobs) */\n");
    ts.push_str("export const declaredCredentials = [\n");
    for (service, env_var) in &declared {
        ts.push_str(&format!("  {{ service: '{service}', envVar: '{env_var}' }},\n"));
    }
    ts.push_str("] as const;\n\n");

    ts.push_str("/**\n");
    ts.push_str(" * W4 tenant credential store: stored credentials layer over the env\n");
    ts.push_str(" * (store \u{2192} env \u{2192} unconfigured). Called at boot when\n");
    ts.push_str(" * ALMADAR_CREDENTIAL_MASTER_KEY is configured (see server index).\n");
    ts.push_str(" * With ALMADAR_CREDENTIALS_SOURCE=store the store is the only source and the\n");
    ts.push_str(" * declared credentials the store lacks are seeded from the env once.\n");
    ts.push_str(" */\n");
    ts.push_str("export async function installTenantCredentialStore(adapter: CredentialPersistence): Promise<void> {\n");
    ts.push_str("  const store = new CredentialStore(adapter);\n");
    ts.push_str("  installCredentialStore(store);\n");
    ts.push_str("  await store.warm();\n");
    ts.push_str("  if (credentialsFromStoreOnly(process.env)) await seedCredentialStore(store, declaredCredentials, process.env, await loadInstalledKernel());\n");
    ts.push_str("}\n\n");

    // Also export the service names for type safety
    ts.push_str("/** Services declared in this schema */\n");
    ts.push_str("export const declaredServices = [\n");
    for service_ref in services {
        if let ServiceRef::Inline(service_def) = service_ref {
            let name = match service_def {
                ServiceDefinition::Rest(rest) => &rest.name,
                ServiceDefinition::Socket(socket) => &socket.name,
                ServiceDefinition::Mcp(mcp) => &mcp.name,
            };
            ts.push_str(&format!("  '{}',\n", name));
        }
    }
    ts.push_str("] as const;\n\n");

    ts.push_str("/** Services this schema actually invokes via call-service — drives the boot-time credential check and /health */\n");
    ts.push_str("export const invokedServices = [\n");
    for name in invoked {
        ts.push_str(&format!("  '{}',\n", name));
    }
    ts.push_str("] as const;\n");

    ts
}


/// The `(service, env var)` of every credential the app declares: the registry's for the invoked services, then the
/// program's own, each env var once.
fn declared_credentials(invoked: &BTreeSet<String>, program: &[ProgramCredential]) -> Vec<(String, String)> {
    let registry = orbital_core_base::language::registry::baked_service_credentials();
    let mut out: Vec<(String, String)> = Vec::new();
    let registered = invoked.iter().flat_map(|name| registry.get(name).into_iter().flatten().map(move |c| (name.clone(), c.env_var.clone())));
    let own = program.iter().map(|c| (c.group.clone(), c.env_var.clone()));
    for (service, env_var) in registered.chain(own) {
        if !out.iter().any(|(_, held)| *held == env_var) {
            out.push((service, env_var));
        }
    }
    out
}

/// Collect the service names this module invokes via `call-service` effects
/// (transitions + ticks), at ANY depth — nested forms inside expression args
/// (the `llm embed` class, I-8) count, same coverage as effect validation.
pub fn collect_invoked_services(module: &OirModule) -> BTreeSet<String> {
    module.invoked_services()
}

/// Generate the per-app credential manifest for the services the schema
/// invokes: a `packages/server/.env.example` block and a `SECRETS.md` deploy
/// manifest (env var table + `firebase apphosting:secrets:set` commands).
/// Returns `None` when the schema invokes no services, or none of the invoked
/// services declare credentials.
pub fn generate_env_manifest(module: &OirModule) -> Option<(String, String)> {
    let invoked = collect_invoked_services(module);
    if invoked.is_empty() {
        return None;
    }

    let registry = orbital_core_base::language::registry::baked_service_credentials();
    let with_creds: Vec<(&String, &Vec<orbital_core_base::language::registry::EmbeddedServiceCredential>)> =
        invoked
            .iter()
            .filter_map(|name| registry.get(name).filter(|c| !c.is_empty()).map(|c| (name, c)))
            .collect();
    if with_creds.is_empty() {
        return None;
    }

    let mut env = String::new();
    env.push_str("# Integration credentials — generated from the services this app invokes.\n");
    env.push_str("# Copy to packages/server/.env for local development; production values\n");
    env.push_str("# come from the platform secret store (see SECRETS.md).\n");
    for (service, creds) in &with_creds {
        env.push_str(&format!("\n# {service}\n"));
        for c in creds.iter() {
            let requirement = if c.required { "required" } else { "optional" };
            env.push_str(&format!("# {} ({})\n{}=\n", c.description, requirement, c.env_var));
        }
    }

    let mut md = String::new();
    md.push_str("# Secrets\n\n");
    md.push_str("Generated from the services this app invokes. Each variable below must be\n");
    md.push_str("present in the server environment; required ones fail the boot check when\n");
    md.push_str("missing in production.\n\n");
    md.push_str("| Service | Env var | Required | Description |\n");
    md.push_str("|---|---|---|---|\n");
    for (service, creds) in &with_creds {
        for c in creds.iter() {
            md.push_str(&format!(
                "| {} | `{}` | {} | {} |\n",
                service,
                c.env_var,
                if c.required { "yes" } else { "no" },
                c.description,
            ));
        }
    }
    md.push_str("\n## Firebase App Hosting\n\n");
    md.push_str("```bash\n");
    for (_, creds) in &with_creds {
        for c in creds.iter() {
            md.push_str(&format!("firebase apphosting:secrets:set {}\n", c.env_var));
        }
    }
    md.push_str("```\n\n");
    md.push_str("Then reference each secret from `apphosting.yaml`:\n\n");
    md.push_str("```yaml\n");
    md.push_str("env:\n");
    for (_, creds) in &with_creds {
        for c in creds.iter() {
            md.push_str(&format!(
                "  - variable: {}\n    secret: {}\n",
                c.env_var, c.env_var
            ));
        }
    }
    md.push_str("```\n");

    Some((env, md))
}


#[cfg(test)]
mod tests {
    use super::*;
    use orbital_core_base::schema::{
        AuthKeyLocation, RestAuthConfig, RestAuthType, RestServiceDefInner,
    };

    fn create_test_rest_service() -> ServiceDefinition {
        ServiceDefinition::Rest(RestServiceDefInner {
            name: "openweather".to_string(),
            description: Some("OpenWeather API client".to_string()),
            base_url: "https://api.openweathermap.org/data/2.5".to_string(),
            headers: None,
            auth: Some(RestAuthConfig {
                auth_type: RestAuthType::ApiKey,
                key_name: Some("appid".to_string()),
                location: Some(AuthKeyLocation::Query),
                secret_env: Some("OPENWEATHER_API_KEY".to_string()),
            }),
            timeout: Some(30000),
        })
    }

    #[test]
    fn the_clients_module_installs_the_runtime_credential_store_and_imports_no_integrations() {
        let ts = generate_service_clients(&[], &BTreeSet::new(), &[]);

        assert!(ts.contains("from '@almadar/runtime/credentials'"), "{ts}");
        assert!(ts.contains("installCredentialStore(store)"), "{ts}");
        assert!(ts.contains("await store.warm()"), "{ts}");
        assert!(ts.contains("export const declaredCredentials = [\n] as const;"), "no declared credential, none listed: {ts}");
        assert!(!ts.contains("integrations"), "{ts}");
        assert!(!ts.contains("callService") && !ts.contains("httpCall"), "{ts}");
    }

    #[test]
    fn the_clients_module_seeds_a_store_source_boot_with_the_programs_own_declared_credentials_once() {
        let own = |group: &str, env_var: &str| ProgramCredential { group: group.into(), env_var: env_var.into(), description: String::new() };
        let ts = generate_service_clients(&[], &BTreeSet::new(), &[own("LlmOrbital", "OPENAI_API_KEY"), own("Other", "OPENAI_API_KEY"), own("Mail", "SMTP_PASSWORD")]);

        assert!(ts.contains("{ service: 'LlmOrbital', envVar: 'OPENAI_API_KEY' },"), "{ts}");
        assert!(ts.contains("{ service: 'Mail', envVar: 'SMTP_PASSWORD' },"), "{ts}");
        assert_eq!(ts.matches("OPENAI_API_KEY").count(), 1, "a name declared twice lists once: {ts}");
        assert!(ts.contains("import { loadInstalledKernel } from '@almadar/runtime/kernelNode';"), "{ts}");
        assert!(
            ts.contains("if (credentialsFromStoreOnly(process.env)) await seedCredentialStore(store, declaredCredentials, process.env, await loadInstalledKernel());"),
            "the kernel plans the seed: {ts}"
        );
        assert!(!ts.contains("sk-") && !ts.contains("process.env.OPENAI"), "names only, never a value: {ts}");
    }

    #[test]
    fn test_declared_services_lists_all_services() {
        let services = vec![ServiceRef::Inline(create_test_rest_service())];
        let ts = generate_service_clients(&services, &BTreeSet::new(), &[]);

        assert!(ts.contains("declaredServices"));
        assert!(ts.contains("'openweather'"));
    }

    #[test]
    fn test_invoked_services_listed() {
        let invoked: BTreeSet<String> = ["email".to_string(), "twilio".to_string()]
            .into_iter()
            .collect();
        let ts = generate_service_clients(&[], &invoked, &[]);

        assert!(ts.contains("invokedServices"));
        assert!(ts.contains("  'email',\n  'twilio',\n"));
    }

}
