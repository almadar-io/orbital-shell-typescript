//! Service Client Code Generation
//!
//! Generates TypeScript service clients that delegate to @almadar/integrations.
//! This replaces the old raw-fetch codegen with a unified integration layer that
//! provides retry, validation, structured errors, and centralized credential management.

use orbital_core::ir::{OirEffect, OirExpr, OirModule};
use orbital_core::schema::{ServiceDefinition, ServiceRef};
use std::collections::BTreeSet;

/// Generate a TypeScript service client module that delegates to @almadar/integrations.
///
/// Instead of generating raw fetch() clients, we import the RuntimeIntegrationManager
/// which provides retry, validation, structured errors, and centralized credential management.
///
/// `http_egress` is `Some(origins)` when the program runs an `http` effect: the module then also
/// exports `httpCall`, the one function every generated `http` site calls, with the program's
/// egress list. `None` emits no http support (and imports nothing from `@almadar/kernel`).
pub fn generate_service_clients(
    services: &[ServiceRef],
    invoked: &BTreeSet<String>,
    http_egress: Option<&[String]>,
) -> String {
    let mut ts = String::new();

    ts.push_str("/**\n");
    ts.push_str(" * Service Clients - Generated by Orbital Compiler\n");
    ts.push_str(" *\n");
    ts.push_str(" * Delegates to @almadar/integrations for retry, validation,\n");
    ts.push_str(" * structured errors, and centralized credential management.\n");
    ts.push_str(" */\n\n");

    ts.push_str("import { RuntimeIntegrationManager } from '@almadar/integrations/runtime';\n");
    if http_egress.is_some() {
        ts.push_str("import { CredentialStore, type CredentialPersistence } from '@almadar/integrations';\n");
        ts.push_str("import { createRequire } from 'node:module';\n");
        ts.push_str("import { dirname, join } from 'node:path';\n");
        ts.push_str("import type { HttpFailurePayload, JsonValue, RuntimeValue } from '@almadar/core';\n");
        ts.push_str("import { createHttpPorts, credentialForgetPayload, credentialStatusPayload, randomBytesPayload, runHttpCall, type HttpCall, type HttpRunOptions } from '@almadar/runtime/kernel';\n");
        ts.push_str("import { loadHttpKernel } from '@almadar/runtime/kernelNode';\n\n");
    } else {
        ts.push_str("import { CredentialStore, type CredentialPersistence } from '@almadar/integrations';\n\n");
    }

    ts.push_str("const manager = new RuntimeIntegrationManager();\n");
    ts.push_str("manager.configureFromEnv();\n\n");

    ts.push_str("/**\n");
    ts.push_str(" * W4 tenant credential store: layer stored credentials over the env\n");
    ts.push_str(" * (store \u{2192} env \u{2192} unconfigured) and keep them live on change. Called at\n");
    ts.push_str(" * boot when ALMADAR_CREDENTIAL_MASTER_KEY is configured (see server index).\n");
    ts.push_str(" */\n");
    ts.push_str("export async function installTenantCredentialStore(adapter: CredentialPersistence): Promise<void> {\n");
    ts.push_str("  await manager.configureFromStore(new CredentialStore(adapter));\n");
    ts.push_str("}\n\n");

    ts.push_str("/**\n");
    ts.push_str(" * Call an external service action.\n");
    ts.push_str(" *\n");
    ts.push_str(" * @param service - Service name (e.g., 'stripe', 'llm')\n");
    ts.push_str(" * @param action - Action name (e.g., 'createPaymentIntent')\n");
    ts.push_str(" * @param params - Action parameters\n");
    ts.push_str(" */\n");
    ts.push_str("export const callService = manager.getCallServiceHandler();\n\n");

    if let Some(egress) = http_egress {
        ts.push_str(&generate_http_call(egress));
    }

    // Also export the service names for type safety
    ts.push_str("/** Services declared in this schema */\n");
    ts.push_str("export const declaredServices = [\n");
    for service_ref in services {
        if let ServiceRef::Inline(service_def) = service_ref {
            let name = match service_def {
                ServiceDefinition::Rest(rest) => &rest.name,
                ServiceDefinition::Socket(socket) => &socket.name,
                ServiceDefinition::Mcp(mcp) => &mcp.name,
            };
            ts.push_str(&format!("  '{}',\n", name));
        }
    }
    ts.push_str("] as const;\n\n");

    ts.push_str("/** Services this schema actually invokes via call-service — drives the boot-time credential check and /health */\n");
    ts.push_str("export const invokedServices = [\n");
    for name in invoked {
        ts.push_str(&format!("  '{}',\n", name));
    }
    ts.push_str("] as const;\n");

    ts
}

/// `packages/server/src/services/host.ts`: where the route module lends the
/// running app to service calls (`llm call-tools`) and where a `call-service`
/// site finds it, as the caller. A module of its own so handlers and the route
/// share it without importing each other.
pub fn generate_service_host() -> String {
    let mut ts = String::new();
    ts.push_str("/**\n");
    ts.push_str(" * Service host — Generated by Orbital Compiler\n");
    ts.push_str(" *\n");
    ts.push_str(" * The running app, lent to a service call as the caller: the declared\n");
    ts.push_str(" * inputs, the input channel, a `@read`-filtered read, and the route a\n");
    ts.push_str(
        " * running call's live messages (`emit.onMessage`) take to the requesting tab —\n",
    );
    ts.push_str(" * and the registry of keyed in-flight calls `cancel-call` aborts.\n");
    ts.push_str(" */\n\n");
    ts.push_str("import type { EventPayload, ServiceHostPorts, UserContext } from '@almadar/core';\n\n");
    ts.push_str("export type ServiceCaller = ServiceHostPorts['caller'];\n");
    ts.push_str("export type ServicePortsFactory = (caller: ServiceCaller, user: UserContext | undefined, message: (payload: EventPayload) => void) => ServiceHostPorts;\n\n");
    ts.push_str("let lent: ServicePortsFactory | undefined;\n\n");
    ts.push_str("export function lendServiceHost(factory: ServicePortsFactory): void {\n");
    ts.push_str("  lent = factory;\n");
    ts.push_str("}\n\n");
    ts.push_str("export function servicePorts(caller: ServiceCaller, user: UserContext | undefined, message: (payload: EventPayload) => void = () => {}): ServiceHostPorts | undefined {\n");
    ts.push_str("  return lent?.(caller, user, message);\n");
    ts.push_str("}\n\n");
    ts.push_str("const inFlight = new Map<string, Set<AbortController>>();\n\n");
    ts.push_str("export function beginKeyedCall(key: string): AbortController {\n");
    ts.push_str("  const controller = new AbortController();\n");
    ts.push_str("  const running = inFlight.get(key);\n");
    ts.push_str("  if (running) {\n");
    ts.push_str("    running.add(controller);\n");
    ts.push_str("  } else {\n");
    ts.push_str("    inFlight.set(key, new Set([controller]));\n");
    ts.push_str("  }\n");
    ts.push_str("  return controller;\n");
    ts.push_str("}\n\n");
    ts.push_str("export function endKeyedCall(key: string, controller: AbortController): void {\n");
    ts.push_str("  const running = inFlight.get(key);\n");
    ts.push_str("  if (!running) return;\n");
    ts.push_str("  running.delete(controller);\n");
    ts.push_str("  if (running.size === 0) inFlight.delete(key);\n");
    ts.push_str("}\n\n");
    ts.push_str("export function cancelKeyedCall(key: string): void {\n");
    ts.push_str("  const running = inFlight.get(key);\n");
    ts.push_str("  if (!running) return;\n");
    ts.push_str("  for (const controller of running) {\n");
    ts.push_str("    controller.abort();\n");
    ts.push_str("  }\n");
    ts.push_str("}\n");
    ts
}

/// `httpCall`: the generated app's one entry to the `http` effect. `@almadar/kernel`'s step machine
/// (`httpDriverStart`/`httpDriverResume`) owns the request, OAuth, pagination and framing; the shared
/// transport in `@almadar/runtime/kernel` answers its asks (credential store, pinned fetch). This
/// function only loads the kernel and turns a failed outcome into the error the call site catches.
fn generate_http_call(egress: &[String]) -> String {
    let mut ts = String::new();
    ts.push_str("/** Origins the program's `http` effects may reach (the schema's `egress`) */\n");
    ts.push_str("export const httpEgress: readonly string[] = [\n");
    for origin in egress {
        ts.push_str(&format!("  '{}',\n", origin));
    }
    ts.push_str("];\n\n");
    ts.push_str("const httpPorts = createHttpPorts({\n");
    ts.push_str("  kernel: () => loadHttpKernel(join(dirname(createRequire(import.meta.url).resolve('@almadar/kernel')), '..')),\n");
    ts.push_str("  egress: httpEgress,\n");
    ts.push_str("});\n\n");
    ts.push_str("export class HttpCallError extends Error {\n");
    ts.push_str("  constructor(readonly payload: HttpFailurePayload) {\n");
    ts.push_str("    super(payload.error);\n");
    ts.push_str("  }\n");
    ts.push_str("  get kind(): HttpFailurePayload['kind'] {\n");
    ts.push_str("    return this.payload.kind;\n");
    ts.push_str("  }\n");
    ts.push_str("  get key(): string | null {\n");
    ts.push_str("    return this.payload.key;\n");
    ts.push_str("  }\n");
    ts.push_str("}\n\n");
    ts.push_str("export async function httpCall(call: HttpCall, options: HttpRunOptions): Promise<JsonValue> {\n");
    ts.push_str("  const outcome = await runHttpCall(httpPorts, call, options);\n");
    ts.push_str("  if ('error' in outcome) throw new HttpCallError(outcome.error);\n");
    ts.push_str("  return outcome.ok;\n");
    ts.push_str("}\n\n");
    ts.push_str("/** `random-bytes`: `{ value }` from the host CSPRNG. */\n");
    ts.push_str("export function hostRandomBytes(bytes: RuntimeValue): { value: string } {\n");
    ts.push_str("  return randomBytesPayload(httpPorts, bytes);\n");
    ts.push_str("}\n\n");
    ts.push_str("/** `credential-status`: `{ connected }` for the signed-in viewer. */\n");
    ts.push_str("export function hostCredentialStatus(credential: RuntimeValue, principal: string | undefined): Promise<{ connected: boolean }> {\n");
    ts.push_str("  return credentialStatusPayload(httpPorts, credential, principal);\n");
    ts.push_str("}\n\n");
    ts.push_str("/** `credential-forget`: drops the signed-in viewer's credential. */\n");
    ts.push_str("export function hostCredentialForget(credential: RuntimeValue, principal: string | undefined): Promise<{ connected: false }> {\n");
    ts.push_str("  return credentialForgetPayload(httpPorts, credential, principal);\n");
    ts.push_str("}\n\n");
    ts
}

/// Collect the service names this module invokes via `call-service` effects
/// (transitions + ticks), at ANY depth — nested forms inside expression args
/// (the `llm embed` class, I-8) count, same coverage as effect validation.
pub fn collect_invoked_services(module: &OirModule) -> BTreeSet<String> {
    module.invoked_services()
}

/// Generate the per-app credential manifest for the services the schema
/// invokes: a `packages/server/.env.example` block and a `SECRETS.md` deploy
/// manifest (env var table + `firebase apphosting:secrets:set` commands).
/// Returns `None` when the schema invokes no services, or none of the invoked
/// services declare credentials.
pub fn generate_env_manifest(module: &OirModule) -> Option<(String, String)> {
    let invoked = collect_invoked_services(module);
    if invoked.is_empty() {
        return None;
    }

    let registry = orbital_core::language::registry::baked_service_credentials();
    let with_creds: Vec<(&String, &Vec<orbital_core::language::registry::EmbeddedServiceCredential>)> =
        invoked
            .iter()
            .filter_map(|name| registry.get(name).filter(|c| !c.is_empty()).map(|c| (name, c)))
            .collect();
    if with_creds.is_empty() {
        return None;
    }

    let mut env = String::new();
    env.push_str("# Integration credentials — generated from the services this app invokes.\n");
    env.push_str("# Copy to packages/server/.env for local development; production values\n");
    env.push_str("# come from the platform secret store (see SECRETS.md).\n");
    for (service, creds) in &with_creds {
        env.push_str(&format!("\n# {service}\n"));
        for c in creds.iter() {
            let requirement = if c.required { "required" } else { "optional" };
            env.push_str(&format!("# {} ({})\n{}=\n", c.description, requirement, c.env_var));
        }
    }

    let mut md = String::new();
    md.push_str("# Secrets\n\n");
    md.push_str("Generated from the services this app invokes. Each variable below must be\n");
    md.push_str("present in the server environment; required ones fail the boot check when\n");
    md.push_str("missing in production.\n\n");
    md.push_str("| Service | Env var | Required | Description |\n");
    md.push_str("|---|---|---|---|\n");
    for (service, creds) in &with_creds {
        for c in creds.iter() {
            md.push_str(&format!(
                "| {} | `{}` | {} | {} |\n",
                service,
                c.env_var,
                if c.required { "yes" } else { "no" },
                c.description,
            ));
        }
    }
    md.push_str("\n## Firebase App Hosting\n\n");
    md.push_str("```bash\n");
    for (_, creds) in &with_creds {
        for c in creds.iter() {
            md.push_str(&format!("firebase apphosting:secrets:set {}\n", c.env_var));
        }
    }
    md.push_str("```\n\n");
    md.push_str("Then reference each secret from `apphosting.yaml`:\n\n");
    md.push_str("```yaml\n");
    md.push_str("env:\n");
    for (_, creds) in &with_creds {
        for c in creds.iter() {
            md.push_str(&format!(
                "  - variable: {}\n    secret: {}\n",
                c.env_var, c.env_var
            ));
        }
    }
    md.push_str("```\n");

    Some((env, md))
}

/// Generate `packages/server/src/hooks-providers.ts` — the inbound-hook
/// provider map derived from the services this app invokes × the registry's
/// hook declarations (I-26). Always emitted (empty map when no invoked
/// service declares hooks) so the template server can unconditionally import
/// it; the checked-in template stub keeps standalone CI builds green.
pub fn generate_hooks_providers(invoked: &BTreeSet<String>) -> String {
    let registry = orbital_core::language::registry::baked_service_hooks();
    let mut hooks: Vec<&orbital_core::language::registry::EmbeddedServiceHook> = invoked
        .iter()
        .filter_map(|name| registry.get(name))
        .flatten()
        .collect();
    hooks.sort_by(|a, b| a.provider.cmp(&b.provider));
    hooks.dedup_by(|a, b| a.provider == b.provider);

    let mut ts = String::new();
    ts.push_str("/**\n");
    ts.push_str(" * Hook Providers - Generated by Orbital Compiler\n");
    ts.push_str(" *\n");
    ts.push_str(" * Inbound-webhook providers derived from the services this app invokes.\n");
    ts.push_str(" * Each provider verifies its own signature/channel token; the hooks router\n");
    ts.push_str(" * mounts them at POST /api/hooks/:provider OUTSIDE the authenticated scope.\n");
    ts.push_str(" */\n\n");

    if hooks.is_empty() {
        ts.push_str("export function hookProviders() {\n  return {};\n}\n");
        return ts;
    }

    let mut exports: Vec<&str> = hooks.iter().map(|h| h.provider_export.as_str()).collect();
    exports.sort_unstable();
    exports.dedup();
    ts.push_str(&format!(
        "import {{ {} }} from '@almadar/integrations';\n\n",
        exports.join(", ")
    ));
    ts.push_str("export function hookProviders() {\n  return {\n");
    for h in &hooks {
        ts.push_str(&format!(
            "    '{}': {}(process.env.{}),\n",
            h.provider, h.provider_export, h.credential_env
        ));
    }
    ts.push_str("  };\n}\n");
    ts
}

/// Extract inline services from service refs
pub fn extract_inline_services(services: &[ServiceRef]) -> Vec<&ServiceDefinition> {
    services
        .iter()
        .filter_map(|s| match s {
            ServiceRef::Inline(def) => Some(def),
            // Object and Reference forms should have been resolved to
            // Inline by the inline phase before reaching codegen. If one
            // does slip through, skip it (it's a non-fatal codegen miss
            // rather than an unreachable! that would crash builds).
            ServiceRef::Object(_) => None,
            ServiceRef::Reference(_) => None,
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use orbital_core::schema::{
        AuthKeyLocation, RestAuthConfig, RestAuthType, RestServiceDefInner,
    };

    fn create_test_rest_service() -> ServiceDefinition {
        ServiceDefinition::Rest(RestServiceDefInner {
            name: "openweather".to_string(),
            description: Some("OpenWeather API client".to_string()),
            base_url: "https://api.openweathermap.org/data/2.5".to_string(),
            headers: None,
            auth: Some(RestAuthConfig {
                auth_type: RestAuthType::ApiKey,
                key_name: Some("appid".to_string()),
                location: Some(AuthKeyLocation::Query),
                secret_env: Some("OPENWEATHER_API_KEY".to_string()),
            }),
            timeout: Some(30000),
        })
    }

    #[test]
    fn test_generate_service_clients_uses_integration_manager() {
        let services = vec![ServiceRef::Inline(create_test_rest_service())];
        let ts = generate_service_clients(&services, &BTreeSet::new(), None);

        assert!(ts.contains("RuntimeIntegrationManager"));
        assert!(ts.contains("@almadar/integrations/runtime"));
        assert!(ts.contains("configureFromEnv"));
        assert!(ts.contains("callService"));
        assert!(ts.contains("'openweather'"));
    }

    #[test]
    fn http_support_is_absent_unless_the_program_runs_http() {
        let ts = generate_service_clients(&[], &BTreeSet::new(), None);
        assert!(!ts.contains("httpCall"), "{ts}");
        assert!(!ts.contains("@almadar/runtime/kernel"), "{ts}");
    }

    #[test]
    fn http_call_is_exported_with_the_schema_egress_and_delegates_to_the_kernel() {
        let egress = vec!["https://api.iconify.design".to_string(), "https://api.example.com:8443".to_string()];
        let ts = generate_service_clients(&[], &BTreeSet::new(), Some(&egress));
        assert!(ts.contains("export async function httpCall("), "{ts}");
        assert!(ts.contains("export class HttpCallError extends Error"), "{ts}");
        assert!(ts.contains("  'https://api.iconify.design',\n  'https://api.example.com:8443',\n];"), "{ts}");
        assert!(ts.contains("import { createHttpPorts, credentialForgetPayload, credentialStatusPayload, randomBytesPayload, runHttpCall, type HttpCall, type HttpRunOptions } from '@almadar/runtime/kernel';"), "{ts}");
        assert!(ts.contains("export function hostRandomBytes(bytes: RuntimeValue): { value: string }"), "{ts}");
        assert!(ts.contains("export function hostCredentialStatus("), "{ts}");
        assert!(ts.contains("export function hostCredentialForget("), "{ts}");
        assert!(ts.contains("await runHttpCall(httpPorts, call, options)"), "{ts}");
        assert!(!ts.contains("fetch("), "the shared transport owns the network: {ts}");
        assert!(!ts.contains("oauth") && !ts.contains("paginate"), "{ts}");
        assert!(ts.contains("callService = manager.getCallServiceHandler()"), "{ts}");
    }

    #[test]
    fn edge_empty_egress_still_exports_an_empty_allow_list() {
        let ts = generate_service_clients(&[], &BTreeSet::new(), Some(&[]));
        assert!(ts.contains("export const httpEgress: readonly string[] = [\n];"), "{ts}");
    }

    #[test]
    fn test_declared_services_lists_all_services() {
        let services = vec![ServiceRef::Inline(create_test_rest_service())];
        let ts = generate_service_clients(&services, &BTreeSet::new(), None);

        assert!(ts.contains("declaredServices"));
        assert!(ts.contains("'openweather'"));
    }

    #[test]
    fn test_invoked_services_listed() {
        let invoked: BTreeSet<String> = ["email".to_string(), "twilio".to_string()]
            .into_iter()
            .collect();
        let ts = generate_service_clients(&[], &invoked, None);

        assert!(ts.contains("invokedServices"));
        assert!(ts.contains("  'email',\n  'twilio',\n"));
    }

    #[test]
    fn test_hooks_providers_empty_without_hooked_services() {
        let ts = generate_hooks_providers(&BTreeSet::new());
        assert!(ts.contains("export function hookProviders()"));
        assert!(ts.contains("return {};"));
    }

    #[test]
    fn test_hooks_providers_derived_from_invoked_calendar() {
        // Relies on the baked registry's calendar hook declaration (I-26).
        let invoked: BTreeSet<String> = ["calendar".to_string()].into_iter().collect();
        let ts = generate_hooks_providers(&invoked);
        assert!(ts.contains("googleCalendarHookProvider"), "generated:\n{ts}");
        assert!(ts.contains("'google-calendar': googleCalendarHookProvider(process.env.GOOGLE_CALENDAR_CHANNEL_TOKEN)"));
        assert!(ts.contains("from '@almadar/integrations'"));
    }

    #[test]
    fn test_extract_inline_services() {
        let services = vec![
            ServiceRef::Inline(create_test_rest_service()),
            ServiceRef::Reference("Other.services.weather".to_string()),
        ];
        let inline = extract_inline_services(&services);
        assert_eq!(inline.len(), 1);
    }
}
