use orbital_core_base::schema::{ThemeDefinition, ThemeTokens};
use orbital_core_base::str_utils::capitalize_first;



/// Generate consolidated theme config for backward compatibility
///
/// This is the old format that exports CUSTOM_THEMES for DesignThemeProvider.
/// Kept for backward compatibility during migration.
pub fn generate_all_themes_config_ts(
    themes: &[ThemeDefinition],
    default_theme: Option<&str>,
) -> String {
    let mut ts = String::new();

    ts.push_str("/**\n");
    ts.push_str(" * Theme Configuration\n");
    ts.push_str(" * Generated by Orbital Compiler\n");
    ts.push_str(" *\n");
    ts.push_str(" * Import this file and pass to ThemeProvider:\n");
    ts.push_str(" *\n");
    ts.push_str(" * ```tsx\n");
    ts.push_str(" * import { THEMES, DEFAULT_THEME } from './generated/theme-config';\n");
    ts.push_str(" * import { ThemeProvider } from '@almadar/ui/context';\n");
    ts.push_str(" *\n");
    ts.push_str(" * <ThemeProvider themes={THEMES} defaultTheme={DEFAULT_THEME}>\n");
    ts.push_str(" *   <App />\n");
    ts.push_str(" * </ThemeProvider>\n");
    ts.push_str(" * ```\n");
    ts.push_str(" */\n\n");

    // Export theme names for the unified provider
    ts.push_str("import type { UIThemeDefinition } from '@almadar/ui/providers';\n\n");
    ts.push_str("/** Theme definitions for ThemeProvider */\n");
    ts.push_str("export const THEMES: UIThemeDefinition[] = [\n");
    for theme in themes {
        let has_dark = theme
            .variants
            .as_ref()
            .map(|v| v.contains_key("dark"))
            .unwrap_or(false);
        let has_light = !theme_tokens_empty(&theme.tokens);
        let display_name = theme
            .display_name
            .clone()
            .unwrap_or_else(|| capitalize_first(&theme.name));
        ts.push_str(&format!(
            "  {{ name: '{}', displayName: {}, hasLightMode: {}, hasDarkMode: {} }},\n",
            theme.name,
            serde_json::to_string(&display_name).unwrap_or_default(),
            has_light,
            has_dark
        ));
    }
    ts.push_str("];\n\n");

    // Derive ThemeName from theme names directly
    let theme_names: Vec<String> = themes.iter().map(|t| format!("'{}'", t.name)).collect();
    ts.push_str(&format!(
        "export type ThemeName = {};\n\n",
        theme_names.join(" | ")
    ));

    // Default theme + mode: the program's declared default key
    // (`"<base>-<light|dark>"`), else the first collected theme in light mode.
    let (default_base, default_mode) = match default_theme {
        Some(key) => match key.strip_suffix("-dark") {
            Some(base) => (base.to_string(), "dark"),
            None => (
                key.strip_suffix("-light").unwrap_or(key).to_string(),
                "light",
            ),
        },
        None => (
            themes
                .first()
                .map(|t| t.name.clone())
                .unwrap_or_else(|| "wireframe".to_string()),
            "light",
        ),
    };
    ts.push_str(&format!(
        "/** Default theme from orbital schema */\nexport const DEFAULT_THEME = '{}';\n\n",
        default_base
    ));
    ts.push_str(&format!(
        "/** Default color mode */\nexport const DEFAULT_MODE = '{}' as const;\n",
        default_mode
    ));

    ts
}

/// A dark-only preset (the `game-*` family) declares every token under
/// `variants.dark` and leaves the base empty.
fn theme_tokens_empty(t: &ThemeTokens) -> bool {
    serde_json::to_value(t)
        .ok()
        .and_then(|v| v.as_object().map(|o| o.is_empty()))
        .unwrap_or(true)
}

#[cfg(test)]
mod theme_definition_import_tests {
    use super::*;

    /// `@almadar/ui/providers` re-exports `UIThemeDefinition` for generated theme configs;
    /// it has no `ThemeDefinition` (TS2724 in every compiled app's `theme-config.ts`).
    #[test]
    fn the_theme_config_imports_the_name_the_ui_exports() {
        let theme: ThemeDefinition = serde_json::from_value(serde_json::json!({ "name": "orb", "tokens": {} })).unwrap();
        let ts = generate_all_themes_config_ts(&[theme], Some("orb"));
        assert!(ts.contains("import type { UIThemeDefinition } from '@almadar/ui/providers';"), "{ts}");
        assert!(ts.contains("export const THEMES: UIThemeDefinition[] = ["), "{ts}");
    }
}
