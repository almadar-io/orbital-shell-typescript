/**
 * generatePatternTypes — regenerate `@almadar/core/patterns/pattern-types.ts`
 * from the live `patterns-registry.json` after each `patterns` sync run.
 * but is exported as a function so the `patterns` cascade command can call it
 * directly (respecting dryRun) instead of relying on a manual `npx tsx` step.
 *
 * The output file is deterministic: sorted pattern names → sorted union members,
 * so a diff against git always reflects real registry changes.
 */

import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from './config.js';

interface PropSchema {
  required?: boolean;
  types: string[];
}

interface PatternDefinition {
  type?: string;
  propsSchema?: Record<string, PropSchema>;
}

interface PatternsRegistry {
  patterns: Record<string, PatternDefinition>;
}

export function mapPropType(types: string[]): string {
  const tsTypes: string[] = types.map((t) => {
    switch (t) {
      case 'string': return 'string';
      case 'number': return 'number';
      case 'boolean': return 'boolean';
      case 'array': return 'unknown[]';
      case 'object': return 'PatternPropValue';
      // `never[]` parameters: any callback is assignable (an `unknown` argument fits no typed one).
      case 'function': return '((...args: never[]) => unknown)';
      case 'null': return 'null';
      default: return 'unknown';
    }
  });
  if (!tsTypes.includes('string')) tsTypes.push('string');
  // Any prop may be a COMPUTED s-expression in the IR (e.g. ["if", …] picking
  // an asset) — the string member only covers binding strings.
  tsTypes.push('SExpr');
  return tsTypes.join(' | ');
}

function generatePropsInterface(patternName: string, propsSchema: Record<string, PropSchema> | undefined): string {
  if (!propsSchema || Object.keys(propsSchema).length === 0) {
    return `  '${patternName}': { type: '${patternName}'; };`;
  }

  const props = Object.entries(propsSchema)
    .filter(([propName]) => propName !== 'type')
    .map(([propName, schema]) => {
      const tsType = mapPropType(schema.types ?? []);
      const optional = !schema.required ? '?' : '';
      const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(propName) ? propName : `'${propName}'`;
      return `    ${key}${optional}: ${tsType};`;
    });

  return [
    `  '${patternName}': {`,
    `    type: '${patternName}';`,
    ...props,
    `  };`,
  ].join('\n');
}

export interface GeneratePatternTypesResult {
  patternCount: number;
  outputPath: string;
}

export function generatePatternTypes(dryRun: boolean): GeneratePatternTypesResult {
  const registryPath = path.join(REPO_ROOT, 'orbital-rust/crates/orbital-shell-typescript/core/src/patterns/patterns-registry.json');
  const outputPath = path.join(REPO_ROOT, 'orbital-rust/crates/orbital-shell-typescript/core/src/patterns/pattern-types.ts');

  const registry: PatternsRegistry = JSON.parse(fs.readFileSync(registryPath, 'utf-8'));
  const patternNames = Object.keys(registry.patterns).sort();

  const propsInterfaces = patternNames.map((name) =>
    generatePropsInterface(name, registry.patterns[name].propsSchema),
  );

  const tsContent = `/**
 * Pattern Types (Auto-Generated)
 *
 * DO NOT EDIT MANUALLY — regenerated by almadar-pattern-sync \`patterns\` command.
 *
 * Generated: ${new Date().toISOString()}
 * Pattern count: ${patternNames.length}
 */

import type { FieldValue } from '../types/entity.js';
import type { SExpr } from '../types/expression.js';

/**
 * Object-typed pattern prop value. Represents dynamic config objects
 * within pattern props (e.g., style, assetManifest, payload).
 */
export type PatternPropValue = Record<string, FieldValue | undefined>;

/**
 * All valid pattern type names from @almadar/core/patterns registry.
 * Use this type in render-ui effects for compile-time validation.
 */
export type PatternType =
${patternNames.map((name) => `  | '${name}'`).join('\n')};

/**
 * Pattern props map — each pattern type maps to its valid props interface.
 */
export interface PatternPropsMap {
${propsInterfaces.join('\n')}
}

/**
 * Get the props type for a specific pattern.
 */
export type PatternProps<T extends PatternType> = PatternPropsMap[T];

/**
 * Type-safe pattern configuration.
 */
export type PatternConfig<T extends PatternType = PatternType> = PatternPropsMap[T];

/**
 * Discriminated union of all pattern configs.
 */
export type AnyPatternConfig = PatternPropsMap[PatternType];

/**
 * Array of all pattern type names (for runtime validation).
 */
export const PATTERN_TYPES: PatternType[] = [
${patternNames.map((name) => `  '${name}',`).join('\n')}
];

/**
 * Check if a string is a valid pattern type.
 */
export function isValidPatternType(type: string): type is PatternType {
  return PATTERN_TYPES.includes(type as PatternType);
}
`;

  if (!dryRun) {
    fs.writeFileSync(outputPath, tsContent);
  }

  return { patternCount: patternNames.length, outputPath };
}
